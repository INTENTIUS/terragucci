const commit = (dir: string, m: string): string => {
  git(dir, "add", "-A");
  git(dir, "-c", "user.name=t", "-c", "user.email=t@t", "-c", "commit.gpgsign=false", "commit", "-q", "--allow-empty", "-m", m);
  return git(dir, "rev-parse", "HEAD").trim();
};

/**
 * origin with main (two roots) and a branch `feature` that changes network,
 * and a checkout of main, as the comment's job has it. `behind` moves main on
 * after the branch was cut; `pipeline` makes the branch change the pipeline.
 */
function repos(o: { behind?: boolean; pipeline?: boolean } = {}): { work: string; origin: string; head: string; git: Git } {
  const dir = tmp("tg-pr-apply-");
  const origin = join(dir, "origin.git");
  git(dir, "init", "-q", "--bare", "-b", "main", origin);
  const work = join(dir, "work");
  git(dir, "init", "-q", "-b", "main", work);
  git(work, "remote", "add", "origin", origin);
  write(work, { "network/main.tf": backend("network"), "app/main.tf": backend("app"), ".github/workflows/terragucci.yml": "# Generated by terragucci.\n" });
  commit(work, "base");
  git(work, "push", "-q", "origin", "main");
  git(work, "checkout", "-q", "-b", "feature");
  write(work, { "network/extra.tf": "# a change\n", ...(o.pipeline ? { ".github/workflows/terragucci.yml": "# edited\n" } : {}) });
  const head = commit(work, "change network");
  git(work, "push", "-q", "origin", "feature");
  git(work, "checkout", "-q", "main");
  if (o.behind) {
    write(work, { "app/later.tf": "# later\n" });
    commit(work, "later on main");
    git(work, "push", "-q", "origin", "main");
    git(work, "reset", "-q", "--hard", "HEAD~1");
  }
  return { work, origin, head, git: (args) => spawnSync("git", args, { cwd: work, encoding: "utf-8" }) as ReturnType<Git> };
}

interface Sent { method: string; path: string; body?: any }

const OPEN = (head: string, extra: Record<string, unknown> = {}) => ({
  state: "open", merged: false, mergeable: true, mergeable_state: "clean", number: 7, user: { login: "author" }, merge_base: TIP,
  head: { sha: head, ref: "feature", repo: { full_name: "acme/infra" } }, base: { ref: "main" }, ...extra,
});

interface Forge {
  pr: any;
  reviews?: unknown[];
  statuses?: unknown[];
  checkRuns?: unknown[];
  permission?: Record<string, string>;
  others?: Record<number, string>;
  /** Answers to the later reads of pull request 7, one each, the last repeated; the first read answers `pr`. */
  later?: any[];
  /** How many commits the head is behind main, as GitHub's compare says. */
  behind?: number;
  /** The pull request's commits, as GitHub lists them. */
  commits?: unknown[];
}

/** main's tip on the forge, which an undiverged Forgejo pull request has as its merge base. */
const TIP = "e".repeat(40);

function setup(comment: string, f: Forge, forgejo = false): { env: NodeJS.ProcessEnv; fetch: Fetch; sent: Sent[] } {
  const dir = tmp("tg-pr-apply-event-");
  const file = join(dir, "event.json");
  writeFileSync(file, JSON.stringify({
    action: "created",
    comment: { body: comment, user: { login: "dev" } },
    issue: { number: 7, pull_request: {} },
    repository: { full_name: "acme/infra", default_branch: "main", ...(forgejo ? { permissions: { push: true, admin: false } } : {}) },
    ...(forgejo ? { sender: { login: "dev" } } : {}),
  }));
  const sent: Sent[] = [];
  const fetch: Fetch = async (url, init) => {
    const path = url.replace("https://forge.test/api/v1/", "");
    sent.push({ method: init?.method ?? "GET", path, body: init?.body ? JSON.parse(init.body) : undefined });
    const answer = (status: number, json: unknown) => ({ ok: status < 300, status, json: async () => json, text: async () => JSON.stringify(json) });
    const perm = /collaborators\/([^/]+)\/permission/.exec(path);
    if (perm) return answer(200, { permission: f.permission?.[decodeURIComponent(perm[1]!)] ?? "write" }) as never;
    if (path.includes("/reviews")) return answer(200, f.reviews ?? []) as never;
    if (path.includes("pulls/7/commits")) return answer(200, f.commits ?? []) as never;
    if (path.endsWith("/status")) return answer(200, { statuses: f.statuses ?? [] }) as never;
    // A commit's statuses as a list, which chant's client reads (chant#4554); GitHub's list is newest first.
    if (/\/commits\/[0-9a-f]+\/statuses(\?|$)/.test(path)) return answer(200, /[?&]page=([2-9]|\d\d)/.test(path) ? [] : [...(f.statuses ?? [])].reverse()) as never;
    if (path.includes("/check-runs")) return answer(200, { check_runs: f.checkRuns ?? [] }) as never;
    if (/pulls\?state=open/.test(path)) return answer(200, [f.pr]) as never;
    if (path.includes("/compare/")) return answer(200, { behind_by: f.behind ?? 0 }) as never;
    if (path.endsWith("/branches/main")) return answer(200, { commit: { id: TIP } }) as never;
    const other = /pulls\/(\d+)$/.exec(path);
    if (other && Number(other[1]) !== 7) return answer(200, { state: f.others?.[Number(other[1])] ?? "closed" }) as never;
    if (path.endsWith("pulls/7")) {
      const reads = sent.filter((x) => x.path.endsWith("pulls/7")).length;
      return answer(200, reads === 1 || !f.later?.length ? f.pr : f.later[Math.min(reads - 2, f.later.length - 1)]) as never;
    }
    return answer(201, {}) as never;
  };
  return { env: { GITHUB_EVENT_PATH: file, GITHUB_REPOSITORY: "acme/infra", GITHUB_API_URL: "https://forge.test/api/v1", TG_TOKEN: "t" }, fetch, sent };
}

const replies = (s: { sent: Sent[] }): string[] => s.sent.filter((x) => x.method === "POST" && x.path.endsWith("/comments")).map((x) => x.body.body as string);

// The decision of an open pull request's `/terragucci apply`, and its merge, are chant's (the comment job); terragucci keeps the reach and the pr-lock job.
describe("apply.when: pull-request in a Terragrunt repo", () => {
  const unit = (deps = ""): string => `include "root" {\n  path = find_in_parent_folders("root.hcl")\n}\n${deps}`;
  const tgLayers = [["live/canary/one"], ["live/fleet/three", "live/fleet/two"]];
  /** origin with three units, live/fleet/two reading live/canary/one through a dependency block, and a branch `feature` with `change`. */
  const tgRepos = (change: Record<string, string>): ReturnType<typeof repos> => {
    const dir = tmp("tg-pr-apply-tg-");
    const origin = join(dir, "origin.git");
    git(dir, "init", "-q", "--bare", "-b", "main", origin);
    const work = join(dir, "work");
    git(dir, "init", "-q", "-b", "main", work);
    git(work, "remote", "add", "origin", origin);
    write(work, {
      "root.hcl": "# shared\n",
      "README.md": "# units\n",
      "live/canary/one/terragrunt.hcl": unit(),
      "live/canary/one/rev.txt": "1\n",
      "live/fleet/two/terragrunt.hcl": unit('dependency "one" {\n  config_path = "../../canary/one"\n}\n'),
      "live/fleet/two/rev.txt": "1\n",
      "live/fleet/three/terragrunt.hcl": unit(),
      "live/fleet/three/rev.txt": "1\n",
      ".github/workflows/terragucci.yml": "# Generated by terragucci.\n",
    });
    commit(work, "base");
    git(work, "push", "-q", "origin", "main");
    git(work, "checkout", "-q", "-b", "feature");
    write(work, change);
    const head = commit(work, "change");
    git(work, "push", "-q", "origin", "feature");
    git(work, "checkout", "-q", "main");
    git(work, "fetch", "-q", "origin");
    return { work, origin, head, git: (args) => spawnSync("git", args, { cwd: work, encoding: "utf-8" }) as ReturnType<Git> };
  };
  const reach = (change: Record<string, string>) => {
    const r = tgRepos(change);
    return reachedUnits(r.git, "origin/main", r.head, tgLayers);
  };

  it("reaches a changed unit and the units whose dependency blocks name it, from git alone", () => {
    expect(reach({ "live/canary/one/rev.txt": "2\n" })).toEqual({ units: ["live/canary/one", "live/fleet/two"] });
    expect(reach({ "live/fleet/two/rev.txt": "2\n" })).toEqual({ units: ["live/fleet/two"] });
    expect(reach({ "live/fleet/three/rev.txt": "2\n", "README.md": "# more\n" })).toEqual({ units: ["live/fleet/three"] });
    // An edge the pull request adds counts, as one it removes would.
    expect(reach({ "live/canary/one/rev.txt": "2\n", "live/fleet/three/terragrunt.hcl": unit('dependencies {\n  paths = ["../../canary/one"]\n}\n') }).units).toEqual(["live/canary/one", "live/fleet/three", "live/fleet/two"]);
  });

  it("a file in no unit's directory reaches every unit, and says which file", () => {
    expect(reach({ "root.hcl": "# changed\n" })).toEqual({ units: ["live/canary/one", "live/fleet/three", "live/fleet/two"], every: "it changes `root.hcl`, which is in no unit's directory" });
  });

});

describe("apply.when: pull-request in an Atmos repo", () => {
  const atmosLayers = [["dev/vpc", "prod/vpc"], ["dev/app", "prod/app"]];
  const edges = (component: string, deps: string[] = []): string => JSON.stringify({ component, dependencies: deps, reads: [] });
  /** origin with the Atmos fixture's files, a branch `feature` with `change`, and a checkout of main where `terragucci atmos write` left the instances. */
  const atmosRepos = (change: Record<string, string>, written = true): ReturnType<typeof repos> => {
    const dir = tmp("tg-pr-apply-atmos-");
    const origin = join(dir, "origin.git");
    git(dir, "init", "-q", "--bare", "-b", "main", origin);
    const work = join(dir, "work");
    git(dir, "init", "-q", "-b", "main", work);
    git(work, "remote", "add", "origin", origin);
    write(work, {
      "atmos.yaml": "base_path: .\n",
      ".gitignore": "/dev/\n/prod/\n",
      "README.md": "# stacks\n",
      "stacks/deploy/prod.yaml": "vars:\n  stage: prod\n",
      "components/terraform/vpc/main.tf": "# vpc\n",
      "components/terraform/app/main.tf": "# app\n",
    });
    commit(work, "base");
    git(work, "push", "-q", "origin", "main");
    git(work, "checkout", "-q", "-b", "feature");
    write(work, change);
    const head = commit(work, "change");
    git(work, "push", "-q", "origin", "feature");
    git(work, "checkout", "-q", "main");
    git(work, "fetch", "-q", "origin");
    if (written) {
      for (const stack of ["dev", "prod"]) {
        write(work, {
          [`${stack}/vpc/.terragucci-atmos.json`]: edges("components/terraform/vpc"),
          [`${stack}/app/.terragucci-atmos.json`]: edges("components/terraform/app", [`${stack}/vpc`]),
        });
      }
    }
    return { work, origin, head, git: (args) => spawnSync("git", args, { cwd: work, encoding: "utf-8" }) as ReturnType<Git> };
  };
  const reach = (change: Record<string, string>, written = true) => {
    const r = atmosRepos(change, written);
    return reachedInstances(r.work, r.git, "origin/main", r.head, atmosLayers);
  };

  it("a change to a component reaches its instances and the instances that depend on them", () => {
    expect(reach({ "components/terraform/app/main.tf": "# app 2\n" })).toEqual({ units: ["dev/app", "prod/app"], kind: "instance" });
    expect(reach({ "components/terraform/vpc/main.tf": "# vpc 2\n", "README.md": "# more\n" })).toEqual({ units: ["dev/app", "dev/vpc", "prod/app", "prod/vpc"], kind: "instance" });
  });

  it("a stack manifest reaches every instance, and says which file", () => {
    expect(reach({ "stacks/deploy/prod.yaml": "vars:\n  stage: prod\n  replicas: 4\n" })).toEqual({
      units: ["dev/app", "dev/vpc", "prod/app", "prod/vpc"],
      every: "it changes `stacks/deploy/prod.yaml`, which can change any Atmos instance",
      kind: "instance",
    });
  });

  it("with no instances written, a component change reaches every instance too", () => {
    expect(reach({ "components/terraform/app/main.tf": "# app 2\n" }, false).every).toBe("it changes `components/terraform/app/main.tf`, which can change any Atmos instance");
  });

  it("reached picks the Atmos reach in a repo with atmos.yaml, and plain roots elsewhere", () => {
    const r = atmosRepos({ "stacks/deploy/prod.yaml": "vars: {}\n" });
    expect(reached(r.work, r.git, "origin/main", r.head, atmosLayers).kind).toBe("instance");
    expect(reached(r.work, r.git, "origin/main", r.head, atmosLayers, { terragrunt: true }).kind).toBe("unit");
  });
});

