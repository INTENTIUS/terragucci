push_as_author() { # dir, repo, branch, message -> prints the pushed sha
  PUSH_NAME="$AUTHOR" PUSH_EMAIL="$AUTHOR@terragucci.local" PUSH_USER="$AUTHOR" PUSH_TOKEN="$AUTHOR_TOKEN" push_quiet "$@"
