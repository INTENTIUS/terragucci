# The commits each loop repo's chant/lifecycle holds, "<repo> <sha>" a line,
# and a line of the repo alone when it has no such branch, for the prune's
# audit.jsonl ledger entries. A repo whose branch cannot be read prints
# nothing, and the prune keeps its entries.
lifecycle_commits() {
  local repo tool remote heads dir ref
  dir="$(mktemp -d "$WORK/c$CYCLE/lifecycle.XXXXXX")" && git init -q --bare "$dir" || return 1
  while read -r repo tool; do
    [ -n "$repo" ] || continue
    remote="${URL/#http:\/\//http://${USER}:${TOKEN}@}/$repo.git"
    heads="$(git ls-remote --heads "$remote" chant/lifecycle 2>/dev/null)" || continue
    if [ -z "$heads" ]; then echo "$repo"; continue; fi
    ref="refs/lifecycle/${repo//\//-}"
    git -C "$dir" fetch -q --no-tags "$remote" "+refs/heads/chant/lifecycle:$ref" 2>/dev/null || continue
    git -C "$dir" rev-list "$ref" | sed "s|^|$repo |"
  done <<<"$(loop_repos)"
}

# Put the repo's chant/lifecycle back to its base before a cycle, as the reset
# puts main back: up writes no such branch, so it is deleted, and the cycle's
# first approval makes it again. Nothing runs on the repo here: the reset
# before waited for its push back's run. The cycle before's gate lines stay
# until now, so behold's kiosk replays them while that cycle is the tool's
# latest. A delete that fails is logged, and the cycle goes on.
lifecycle_back() {
  [ -n "$(remote_head "$REPO" chant/lifecycle)" ] || return 0
  # The last cycle's audit reads this branch.
  housekeeping_wait
  git push -q "$REMOTE" ":refs/heads/chant/lifecycle" 2>/dev/null \
    || log "lifecycle: could not put $REPO's chant/lifecycle back to its base; the cycle goes on"
  return 0
}

# Wait for a copy in the background to finish, from this shell or an earlier
# cycle's. A copy rewrites marks.jsonl from what it read when it started, so a
# mark is appended only once none runs. A copy stops itself after 60 s, so a
# pid that lives longer is not one.
runs_wait() {
  local pid deadline=$(( $(now) + 70 ))
  read -r pid 2>/dev/null <"$RUNS_PID" || return 0
  case "$pid" in ''|*[!0-9]*) return 0 ;; esac
  while kill -0 "$pid" 2>/dev/null && [ "$(now)" -lt "$deadline" ]; do sleep 0.2; done
  return 0
}

runs_export() { # [force], [keep: as runs_copy]
  if [ -z "${1:-}" ]; then
    [ $(( $(now) - RUNS_AT )) -ge 5 ] || return 0
    local pid=""
    read -r pid 2>/dev/null <"$RUNS_PID" || true
    case "$pid" in ''|*[!0-9]*) ;; *) ! kill -0 "$pid" 2>/dev/null || return 0 ;; esac
    RUNS_AT="$(now)"
    mkdir -p "$RUNS_STATE" 2>/dev/null || true
    runs_copy &
    echo "$!" > "$RUNS_PID" 2>/dev/null || true
    return 0
  fi
  runs_wait
  RUNS_AT="$(now)"
  runs_copy "${2:-}"
}

# What the driver did to start run RUN_ID (plan, merge, resume, reset, base or
# push), in this cycle and scenario, for the run's trigger, cycle and scenario
# in the bucket. Then copy the runs at once.
runs_mark() { # trigger, [pull request], [ref]
  mkdir -p "$RUNS_STATE" 2>/dev/null || true
  runs_wait
  jq -cn --argjson id "${RUN_ID:-null}" --arg t "$1" --argjson c "${CYCLE:-null}" --arg s "$SCENARIO" --arg p "${2:-}" --arg r "${3:-}" \
    '{id: $id, trigger: $t, cycle: $c, scenario: (if $s == "" then null else $s end),
      pull: (if $p == "" then null else ($p | tonumber) end)} + (if $r == "" then {} else {ref: $r} end)' \
    >> "$RUNS_STATE/marks.jsonl" 2>/dev/null || log "runs: could not mark run ${RUN_ID:-?} $1"
  runs_export force
}

