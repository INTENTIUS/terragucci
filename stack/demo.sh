ALTER DEFAULT PRIVILEGES FOR ROLE demo_writer GRANT USAGE ON SCHEMAS TO demo_reader;
ALTER DEFAULT PRIVILEGES FOR ROLE demo_writer GRANT SELECT ON TABLES TO demo_reader;
