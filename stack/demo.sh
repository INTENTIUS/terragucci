# A choudoufu tree's record store: one bucket for every estate, each under its
# own prefix, with the settings choudoufu checks before it writes a record
# (versioning, a lifecycle rule for old versions, no public access). choudoufu
# addresses it virtual-hosted, at <bucket>.demo-records, and demo-records
# forwards each request to floci path-style (stack/docker-compose.yml, profile
# demo). up makes it when a tree in the checkout runs on choudoufu.
RECORDS_BUCKET=demo-live-records
# The bucket a choudoufu tool's estates keep their records in. The compose tree has its own, so
# no key of the fan-out tree's meets it.
tool_records_bucket() { # tool
  case "$1" in
    choudoufu-compose) echo demo-choudoufu-compose-records ;;
    terragrunt-choudoufu) echo demo-terragrunt-choudoufu-records ;;
    atmos-choudoufu) echo demo-atmos-choudoufu-records ;;
    *) echo "$RECORDS_BUCKET" ;;
  esac
}
records_up() { # [bucket]
  local RECORDS_BUCKET="${1:-$RECORDS_BUCKET}" ns='xmlns="http://s3.amazonaws.com/doc/2006-03-01/"' xml md5
  curl -s -o /dev/null -X PUT "$FLOCI/$RECORDS_BUCKET" || true
  curl -fsS -o /dev/null -X PUT "$FLOCI/$RECORDS_BUCKET?versioning" -H 'content-type: application/xml' \
    --data-binary "<VersioningConfiguration $ns><Status>Enabled</Status></VersioningConfiguration>" || fail "could not turn on versioning in $RECORDS_BUCKET"
  xml="<LifecycleConfiguration $ns><Rule><ID>expire-noncurrent</ID><Filter><Prefix></Prefix></Filter><Status>Enabled</Status><NoncurrentVersionExpiration><NoncurrentDays>1</NoncurrentDays></NoncurrentVersionExpiration></Rule></LifecycleConfiguration>"
  md5="$(printf '%s' "$xml" | openssl md5 -binary | base64)"
  curl -fsS -o /dev/null -X PUT "$FLOCI/$RECORDS_BUCKET?lifecycle" -H 'content-type: application/xml' -H "Content-MD5: $md5" --data-binary "$xml" \
    || fail "could not set $RECORDS_BUCKET's lifecycle rule"
  curl -fsS -o /dev/null -X PUT "$FLOCI/$RECORDS_BUCKET?publicAccessBlock" -H 'content-type: application/xml' \
    --data-binary "<PublicAccessBlockConfiguration $ns><BlockPublicAcls>true</BlockPublicAcls><IgnorePublicAcls>true</IgnorePublicAcls><BlockPublicPolicy>true</BlockPublicPolicy><RestrictPublicBuckets>true</RestrictPublicBuckets></PublicAccessBlockConfiguration>" \
    || fail "could not block public access to $RECORDS_BUCKET"
}

