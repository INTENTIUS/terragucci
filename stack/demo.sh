  || { echo "SKIP: Docker is not available, so the demo cannot run."; exit 0; }

case "$CMD" in
  down) exec "$HERE/down.sh" ;;
  up|loop) ;;
  *) sed -n '3,/^set -/p' "$0" | grep '^#' | sed 's/^# \{0,1\}//'; exit 2 ;;
esac

