# chant-pr-loop: chant's own pull-request loop, on example-demo-chant/ and the
# pipeline chant generates for it. The plan job (`chant components pr-plan`)
# plans the components the change reaches, network, app and edge here, each on
# the outputs its upstream has now, and posts one note with the digest of the
# whole set and the line that approves it. The gate waits for that approval
# before the merge: the reviewer approves the pull request on Forgejo, and
# records `chant approve pr-<n> pr-apply --plan <digest>` on chant/lifecycle as
# the forge principal the note names, sealed with the reviewer's key. The author
# merges. The apply job (`pr-apply --require-review`) plans the same components
# again, goes on only when the digest is the approved one and its approver has
# an approving review on the pull request, and applies them in dependency
# order: network, app, edge.
#
# What chant's loop does not do yet, and so this scenario does not show: a gate
# per wave after the pull request's plan (--pr-loop refuses --wave-gate,
# chant#4003); a dependent planned on its upstream's planned outputs, so the
# change moves no output a dependent reads (chant#3999); and keeping the
# change's author out of the review count (chant#4000), which the driver never
# tests, since only the reviewer approves.
#
# The forge host chant names reviewers by: Forgejo's ROOT_URL in the stack
# (docker-compose.yml), which the jobs' GITHUB_SERVER_URL carries. up lists the
# reviewer's key under that principal too, in .chant/allowed_signers.
CHANT_FORGE_HOST=forgejo:3000
CHANT_DIGEST="" PLAN_DIGEST="" CHANT_APPROVER="" CHANT_NOTE=""
# The members the plan note must list: chant-pr-loop's three by default; the
# fan-out scenario names its own for each of its two pull requests.
CHANT_MEMBERS="network app edge"

# The plan job's note on the pull request (marker <!-- chant-pr:demo -->):
# the digest it binds, and the approver it names, with the reviewer's login.
chant_note() {
  local deadline=$(( $(now) + 60 )) note="" prefix c
  while :; do
    note="$(api "$URL/api/v1/repos/$REPO/issues/$PULL/comments?limit=50" | jq -r '[.[] | select(.body | startswith("<!-- chant-pr:demo"))][0].body // empty' || true)"
    [ -z "$note" ] || break
    [ "$(now)" -lt "$deadline" ] || fail "the plan run passed but no chant plan note is on pull request $PULL"
    sleep "$POLL"
  done
  CHANT_NOTE="$note"
  CHANT_DIGEST="$(grep -oE -- '--plan jcs1-sha256:[0-9a-f]+' <<<"$note" | awk 'NR == 1 { print $2 }' || true)"
  [ -n "$CHANT_DIGEST" ] || fail "the plan note on pull request $PULL names no digest to approve"
  PLAN_DIGEST="${CHANT_DIGEST:0:20}"
  prefix="$(grep -oE -- '--approver [^ ]*<your-login>' <<<"$note" | awk 'NR == 1 { print $2 }' || true)"
  CHANT_APPROVER="${prefix%<your-login>}$REVIEWER"
  [ "$CHANT_APPROVER" = "forgejo@$CHANT_FORGE_HOST:$REVIEWER" ] \
    || fail "the plan note names approvers as ${prefix:-nothing}, not forgejo@$CHANT_FORGE_HOST:<login>, which .chant/allowed_signers lists"
  for c in $CHANT_MEMBERS; do
    grep -qw -- "$c" <<<"$note" || fail "the plan note on pull request $PULL does not list $c"
  done
}

# The reviewer's approval, the two halves --require-review reads: an approving
# review of the pull request on Forgejo, and the ledger line for the digest,
# from the reviewer's own clone, so the commit chant pushes is the reviewer's.
chant_approve() {
  local clone="$WORK/approve-$CYCLE-pr-$RANDOM" out
  as_reviewer -o /dev/null -H 'content-type: application/json' -X POST \
    -d '{"event":"APPROVED","body":"The plan note shows what this change does."}' \
    "$URL/api/v1/repos/$REPO/pulls/$PULL/reviews" || fail "$REVIEWER could not approve pull request $PULL"
  git clone -q "$REVIEWER_REMOTE" "$clone" 2>/dev/null || fail "$REVIEWER could not clone $REPO"
  git -C "$clone" config user.name "$REVIEWER"
  git -C "$clone" config user.email "$REVIEWER@terragucci.local"
  out="$(cd "$clone" && "$CHANT" approve "pr-$PULL" pr-apply --plan "$CHANT_DIGEST" --approver "$CHANT_APPROVER" --sign "$REVIEWER_KEY" 2>&1)" \
    || { echo "$out" >&2; fail "chant approve pr-$PULL pr-apply failed"; }
}

# Why the apply run did not pass: the pr-apply line of its log, which names
# the refusal (plan-changed, not-approved, not-a-reviewer) or the failure.
chant_refusal() {
  local line
  line="$(run_logs "$REPO" "$RUN_ID" 2>/dev/null | grep -oE 'pr-apply: [a-z-]+( \([a-z-]+\))?' | awk 'NR == 1' || true)"
  echo "the apply ended $RUN_STATUS${line:+, $line} ($RUN_URL)"
}

