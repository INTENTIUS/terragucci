# "<root> <state key>" for each root of a tree: a Terraform root's backend key,
# or a Terragrunt unit's key from the remote_state in root.hcl (the tree's own,
# or the one given, for a scenario's files). A root is a directory one level
# down with a .tf file whose backend names a key, or any directory below with a
# terragrunt.hcl.
tree_keys() { # dir, tool, [root.hcl]
  local dir="$1" f root key template
  case "$2" in
    terraform|chant|tofu-fanout|compose)
      for f in "$dir"/*/*.tf; do
        [ -f "$f" ] || continue
        key="$(awk '/backend "s3"/ { b = 1 } b && /^[[:space:]]*key[[:space:]]*=/ { sub(/^[^"]*"/, ""); sub(/".*/, ""); print; exit }' "$f")"
        [ -z "$key" ] || { root="${f#"$dir"/}"; echo "${root%/*} $key"; }
      done | sort -u ;;
    terragrunt)
      template="$(sed -n 's/^[[:space:]]*key[[:space:]]*=[[:space:]]*"\(.*\)"[[:space:]]*$/\1/p' "${3:-$dir/root.hcl}" 2>/dev/null | awk 'NR == 1')"
      [ -n "$template" ] || return 0
      (cd "$dir" && find . -name terragrunt.hcl -not -path '*/.terragrunt-cache/*' -not -path './scenarios/*' | sed 's#^\./##; s#/terragrunt.hcl$##' | sort) \
        | while read -r root; do echo "$root ${template//\$\{path_relative_to_include()\}/$root}"; done ;;
  esac
}

# The state bucket a tree's roots name: the first bucket in a backend or remote_state.
# It returns on the first bucket rather than piping every file's into head -1:
# under pipefail, head exiting after one line killed the loop still writing the
# next file's bucket with SIGPIPE, and up died with 141 (behold#571).
tree_bucket() { # dir
  local f b
  for f in "$1"/root.hcl "$1"/*/*.tf; do
    [ -f "$f" ] || continue
    b="$(awk '/backend "s3"|remote_state/ { b = 1 } b && /^[[:space:]]*bucket[[:space:]]*=/ { sub(/^[^"]*"/, ""); sub(/".*/, ""); print; exit }' "$f")"
    [ -z "$b" ] || { echo "$b"; return 0; }
  done
}

# Point the driver at a tool's repo: REPO, its remotes, its example tree, the
# directory that keeps its base (the terraform repo's is DEMO_STATE itself, as
# before there were several), its state bucket, BASE_KEYS ("<root> <key>" of
# the roots the base applies), EXTRA_KEYS (those only a scenario's files add,
# which a reset deletes) and ROOTS. INIT_PULL is set when a scenario's pull
# request runs terragucci init after its files, as an author adding units does.
# BASE_RUN is empty for a repo whose base commit starts no run (the chant
# repos' say [skip ci]), so a reset does not wait for one. The fan-out repo's
# roots are its CloudFormation stacks, which have no state bucket or keys.
use_repo() { # tool
  local d keys=""
  TOOL="$1"
  REPO="$USER/$(tool_repo "$1")" || fail "unknown tool '$1'"
  TREE="$(cd "$(tool_tree "$1")" 2>/dev/null && pwd)" || fail "the $1 demo's tree $(tool_tree "$1")/ is not in this checkout"
  REMOTE="${URL/#http:\/\//http://${USER}:${TOKEN}@}/$REPO.git"
  REVIEWER_REMOTE="${URL/#http:\/\//http://${REVIEWER}:${REVIEWER_TOKEN}@}/$REPO.git"
  if [ "$1" = terraform ]; then RSTATE="$DEMO_STATE"; else RSTATE="$DEMO_STATE/repos/${REPO#*/}"; fi
  INIT_PULL="" BASE_RUN=""
  # choudoufu's estates have no state bucket or keys: its roots are the tree's
  # directories with a main.tf, and each reset's push back applies the base.
  ESTATES_DIR=""
  if tool_tgc "$1"; then
    # Three units (network, app, edge), each its own estate in one record store. The base commit says [skip ci].
    STATE_BUCKET="" BASE_KEYS="" EXTRA_KEYS="" INIT_PULL="" BASE_RUN=""
    ROOTS=(network app edge)
    return 0
  fi
  if [ "$1" = choudoufu-fanout ] || [ "$1" = choudoufu-compose ] || [ "$1" = atmos-choudoufu ]; then
    STATE_BUCKET="" BASE_KEYS="" EXTRA_KEYS="" INIT_PULL="" BASE_RUN=1
    # The compose repos' base commit says [skip ci] (its base is applied outside the pipeline), so its push back starts no run.
    [ "$1" != choudoufu-compose ] && [ "$1" != atmos-choudoufu ] || BASE_RUN=
    if [ "$1" = atmos-choudoufu ]; then
      # Three Atmos components, one directory each; the base is applied with atmos, in order.
      ESTATES_DIR=components/terraform
      ROOTS=("$ESTATES_DIR/network" "$ESTATES_DIR/app" "$ESTATES_DIR/edge")
      return 0
    fi
    read -r -a ROOTS <<<"$(tree_roots "$TREE" | tr '\n' ' ')"
    [ "${#ROOTS[@]}" -gt 0 ] || fail "no root with a main.tf is in $TREE"
    return 0
  fi
  if [ "$1" = chant-fanout ] || [ "$1" = chant-compose ]; then
    STATE_BUCKET="" BASE_KEYS="" EXTRA_KEYS=""
    read -r -a ROOTS <<<"$(tree_stacks "$TREE" | tr '\n' ' ')"
    [ "${#ROOTS[@]}" -gt 0 ] || fail "no stack is listed in $TREE/chant.config.ts"
    return 0
  fi
  STATE_BUCKET="$(tree_bucket "$TREE")"
  [ -n "$STATE_BUCKET" ] || fail "no state bucket is named in $TREE"
  BASE_KEYS="$(tree_keys "$TREE" "$1")"
  [ -n "$BASE_KEYS" ] || fail "no root with a state key in $TREE"
  for d in "$TREE"/scenarios/*/pull "$TREE"/scenarios/*/push "$TREE"/scenarios/*/base; do
    [ -d "$d" ] && keys="$keys$(tree_keys "$d" "$1" "$TREE/root.hcl")"$'\n'
  done
  EXTRA_KEYS="$(grep -v '^$' <<<"$keys" | sort -u | grep -vxF -f <(printf '%s\n' "$BASE_KEYS") || true)"
  read -r -a ROOTS <<<"$(awk '{ print $1 }' <<<"$BASE_KEYS" | tr '\n' ' ')"
  [ "$1" != terragrunt ] || INIT_PULL=1
  BASE_RUN=1
  # The chant repo's base commit says [skip ci]: the driver applies it itself.
  [ "$1" != chant ] || BASE_RUN=""
}

