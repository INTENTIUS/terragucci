  esac
}

# "network, app, edge and other": the base's roots, by their last path part.
roots_words() {
  local r out=()
  for r in "${ROOTS[@]}"; do out+=("${r##*/}"); done
  printf '%s, ' "${out[@]}" | sed -E 's/, $//; s/, ([^,]*)$/ and \1/'
}

