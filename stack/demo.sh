# A cycle's housekeeping, in the background once its reset is written, so the
# next cycle opens its pull request while it runs: the cycle's publish (from a
# copy of its timeline), and after cycle_end its audit and the DORA numbers
# (audit_trail, estate_page). It works under <work>/hk, which the loop's
# cleanup of <work>/c<cycle> never touches. Its pid is in <state>/housekeeping.pid.
# What must not overlap it waits for it (housekeeping_wait): the next
# housekeeping, the prune of the bucket's reports, which rewrites the
# audit.jsonl the audit appends to, and putting a chant/lifecycle back, which
# deletes the branch the audit reads. Nothing in it fails the loop.
HK_PID_FILE="$DEMO_STATE/housekeeping.pid"
HK_AUDIT=""
housekeeping_start() { # [after: wait for this tool's background reset first]
  local snap="$DEMO_STATE/timeline.$CYCLE.jsonl" audit="$HK_AUDIT" after="${1:-}"
  HK_AUDIT=""
  cp "$DEMO_STATE/timeline.jsonl" "$snap" 2>/dev/null || : > "$snap"
  housekeeping_wait
  (
    set +e
    WORK="$WORK/hk"
    mkdir -p "$WORK"
    if [ -n "$after" ] && ! bg_reset_wait "$after"; then
      log "housekeeping: cycle $CYCLE's background reset failed; nothing is published for it"
      rm -f "$snap"
      exit 0
    fi
    cycle_publish "$snap"
    if [ -n "$audit" ]; then
      audit_trail
      estate_page
      estate_wait
    fi
    rm -rf "$WORK/c$CYCLE" "$snap"
  ) </dev/null &
  echo "$!" > "$HK_PID_FILE" 2>/dev/null || true
}

housekeeping_wait() {
  local pid deadline=$(( $(now) + LIMIT_HOUSEKEEPING ))
  read -r pid 2>/dev/null <"$HK_PID_FILE" || return 0
  case "$pid" in ''|*[!0-9]*) return 0 ;; esac
  while kill -0 "$pid" 2>/dev/null; do
    if [ "$(now)" -ge "$deadline" ]; then
      log "housekeeping: pid $pid ran past ${LIMIT_HOUSEKEEPING}s; the driver goes on without it"
      break
    fi
    sleep 0.2
  done
  : > "$HK_PID_FILE" 2>/dev/null || true
  return 0
}

# Whether this cycle's reset prunes Forgejo's runs and pull requests and the
# bucket's reports: every PRUNE_EVERY-th cycle. Each prune keeps a fixed number
# (FORGE_RUNS, FORGE_PULLS, REPORTS_KEEP), so between two prunes each grows by
# at most PRUNE_EVERY cycles' worth. The prunes stay in the reset, never beside
# the next cycle: the reports prune rewrites index.json and the other indexes
# that the next cycle's runs write too.
prune_due() { [ "$PRUNE_EVERY" -le 1 ] || [ $(( CYCLE % PRUNE_EVERY )) -eq 0 ]; }

# Check out the step's commit in <VIEWS>/<repo name>.change, once per commit.
# The fetch names the admin's remote on the command line only: no FETCH_HEAD
# and no reflog, so its token is written nowhere in the checkout. --prune drops
# refs/demo-view/* of branches the repo no longer has, so a deleted branch never
# blocks a new one whose name extends it. A checkout that is missing or fails is
# logged, and the step is written all the same.
#
# A commit counts as checked out (VIEW_AT) only once it is. A failed checkout
# used to count, so every later step on the same commit skipped it: the chant
# scenario's four pull-request steps share one commit, and one failure at the
# first left demo-chant.change on the base through all of them (behold#571).
# behold reads a chant checkout by running chant in it, so the driver's checkout
# can meet git's lock there; each step tries a few times, a second apart, and
# the next step tries again. The log line carries git's own reason.
VIEW_AT=""
VIEW_TRIES="${DEMO_VIEW_TRIES:-3}"
view_follow() {
  [ -n "$VIEWS" ] && [ -n "$COMMIT" ] && [ "$REPO:$COMMIT" != "$VIEW_AT" ] || return 0
  local dir="$VIEWS/${REPO##*/}.change" err="" try=0
  if [ ! -d "$dir/.git" ]; then
    log "view: no checkout $dir to put ${COMMIT:0:8} in"
    return 0
  fi
  while :; do
    try=$((try + 1))
    if err="$({ GIT_REFLOG_ACTION="demo view" git -C "$dir" -c core.logAllRefUpdates=false fetch -q --prune --no-write-fetch-head "$REMOTE" '+refs/heads/*:refs/demo-view/*' \
        && git -C "$dir" -c core.logAllRefUpdates=false checkout -q -f --detach "$COMMIT"; } 2>&1)"; then
      VIEW_AT="$REPO:$COMMIT"
      [ -z "$VIEW_OWNER" ] || chown -R "$VIEW_OWNER" "$dir" 2>/dev/null || log "view: could not give $dir to $VIEW_OWNER"
      log "view: $dir at ${COMMIT:0:8}"
      return 0
    fi
    [ "$try" -lt "$VIEW_TRIES" ] || break
    sleep 1
  done
  # git may name the remote, token and all: the log never shows it.
  [ -z "${TOKEN:-}" ] || err="${err//$TOKEN/***}"
  log "view: could not check out ${COMMIT:0:8} in $dir after $try tries; the next step tries again: $(awk '/^(fatal|error):/ && !f { f = $0 } NF { l = $0 } END { print (f != "" ? f : l) }' <<<"$err")"
}

