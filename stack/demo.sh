#!/usr/bin/env bash
#
# The looping demo behold shows: one change across several Terraform states,
# run through the real pipeline on the stack's Forgejo and floci.
#
# Each scenario belongs to a tool, and each tool has its own forge repo pushed
# from its own example tree: terraform's scenarios run on <admin>/demo, from
# example-demo/ (roots network, app, edge and other); terragrunt's on
# <admin>/demo-terragrunt, from example-demo-terragrunt/; chant's on
# <admin>/demo-chant, from example-demo-chant/. A loop walks its scenarios and
# switches repos between them. The roots and their state keys come from each
# tree: a Terraform root's backend key (a chant tree's roots are Terraform
# roots), and a Terragrunt unit's key from root.hcl's remote_state.
#
# The chant repo runs chant's own pull-request pipeline, not terragucci's: its
# .forgejo/workflows/chant-pr.yml is committed in the tree, as generated by
#
#   chant build --components --generate forgejo --pr-loop --env demo \
#     --image terragucci-demo-chant:local --output .forgejo/workflows/chant-pr.yml
#
# at the chant the tree pins (chant#4002 adds --image), and `just
# chant-pipelines` (scripts/chant-pipelines.mjs) fails if the committed file is
# not what that command writes. Its jobs run in terragucci-demo-chant:local, which
# up builds from terragucci's tofu image and the chant the tree pins
# (stack/demo-chant.Dockerfile), so a job downloads no OpenTofu and no chant.
# Its plan job runs `chant
# components pr-plan` on each pull request and its apply job `pr-apply
# --require-review` on each push to main. See the chant scenario below.
#
# The fan-out repo, <admin>/demo-chant-fanout from example-demo-chant-fanout/
# (chant's examples/fan-out-estate), runs the same loop over fifteen
# CloudFormation stacks in floci: network, cluster-a and cluster-b on it, and
# six apps on each cluster. Its pipeline is committed in the tree too, in the
# generator's shape with three more steps (see its header). Its jobs run in
# terragucci-demo-chant-fanout:local (stack/demo-chant-fanout.Dockerfile), the
# tofu image with chant, its aws lexicon and AWS CLI v2. Its stacks have no
# Terraform state: up applies the base with `chant run --components all`, and
# each reset applies the base's templates again, the same way (stacks_back).
# The chant compose repo, <admin>/demo-chant-compose from chant's
# examples/demo-composed-stacks/ (INTENTIUS/chant, read from DEMO_CHANT_TREES or
# a clone under <state>/trees; the tree is not in terragucci), is the
# prompt-driven demo's network, app and edge
# as three CloudFormation stacks in floci. A stock chant project: each stack's
# parameters are filled from the stack before it by `stackOutput` inputs (no
# exports; floci gets those wrong), and its pipeline is the one chant generates
# (`chant build --components --generate forgejo --pr-loop`, see
# scripts/chant-pipelines.mjs), with no terragucci in it. Its jobs run in
# demo-chant-compose:local (stack/demo-chant-compose.Dockerfile),
# which carries chant built from a commit of INTENTIUS/chant (CHANT_COMPOSE_REF)
# since one approval covering a composed run's re-plan is in no release yet.
# Its scenarios are chant-compose-edit and chant-compose-create. Like the other
# chant repos, its base is applied by the driver outside the pipeline and so is
# each reset (stacks_back); the base commit says [skip ci].
# The fan-out repo, <admin>/demo-fanout from example-demo-fanout/, is fifteen
# plain roots of SQS queues and DynamoDB tables in floci: network, cluster-a
# and cluster-b on it, and six apps on each cluster, each with its own state.
# terragucci's pipeline applies it like the terraform repo, in its own image's
# hashicorp/aws mirror (stack/demo-yodel/Dockerfile). Its scenario, fan-out-tofu,
# fails cluster-a at apply and shows a failure blocking only its dependents
# (terragucci#1161). See the fan-out scenario below.
#
# The choudoufu fan-out repo, <admin>/demo-choudoufu-fanout from
# example-demo-choudoufu-fanout/, is the same fifteen as choudoufu estates: no
# state files, each resource's record in the demo's record store. Its scenario,
# fan-out-choudoufu, adds an operator who applies to app-01's estate from
# outside the pipeline while the pipeline's wave applies it, and both land.
# Each reset's push back to the base applies the base tree, which deletes what
# the cycle added; the operator's queue is destroyed first (states_back).
#
# The Terragrunt-on-choudoufu repo, <admin>/demo-terragrunt-choudoufu from
# choudoufu's examples/demo-terragrunt/ (INTENTIUS/choudoufu, read from
# DEMO_CHOUDOUFU_TREES or a clone under <state>/trees; the tree is not in
# terragucci), has no terragucci in it: a Forgejo workflow
# runs Terragrunt's own CLI with choudoufu as its binary, on three units
# (network, app, edge), each a directory with its own terragrunt.hcl, inputs and
# dependency blocks. `terragrunt run --all plan` on the pull request is one joint
# plan, and `terragrunt run --all apply -- tfplan` on the merge is one joint
# apply. Its scenarios are terragrunt-choudoufu-edit and terragrunt-choudoufu-create;
# the approval is a person's approving review, then the merge.
# The choudoufu compose repo, <admin>/demo-choudoufu-compose from
# example-demo-choudoufu-compose/, is example-demo-compose's network, app and
# edge as choudoufu estates on one record store (demo-choudoufu-compose-records,
# its own bucket), with waves.compose on: terragucci composes them through
# choudoufu's composed root, one plan and one apply across estates, with no
# state to pull, split or write back. Its scenarios are choudoufu-compose-edit
# and choudoufu-compose-create. Like the chant repos, its base is applied by the
# driver outside the pipeline, here with choudoufu in the demo image, and so is
# each reset (estates_apply); the base commit says [skip ci].
#
#   stack/demo.sh up                  boot the forgejo profile, and for each
#                                     tool whose tree is in the checkout push
#                                     the tree to its repo, apply its roots, and
#                                     keep the base commit and each root's state
#                                     as that repo's base snapshot. Run once.
#   stack/demo.sh loop [--once] [scenario...]
#                                     run the scenarios one after another and
#                                     reset to the base after each, forever (one
#                                     pass with --once). With no scenario named,
#                                     the ones in DEMO_SCENARIOS (space-separated),
#                                     or else the default three: b-waves, then
#                                     failure, then tg-planned-outputs
#                                     (Terragrunt). Any of ALL_SCENARIOS can be
#                                     named.
#   stack/demo.sh down                remove the stack
#
# The terragrunt-choudoufu, atmos-choudoufu and chant-compose trees are not in
# terragucci: they live in INTENTIUS/choudoufu (examples/demo-terragrunt/,
# examples/demo-atmos/) and INTENTIUS/chant (examples/demo-composed-stacks/).
# DEMO_CHOUDOUFU_TREES and DEMO_CHANT_TREES point at a checkout of each. Without
# them the driver clones the repo into <state>/trees/ and checks out
# DEMO_CHOUDOUFU_TREES_REF / DEMO_CHANT_TREES_REF (default main) on every start.
#
# The roots are network, app (reads network), edge (reads app) and other (reads
# nothing), each terraform_data with its own state. terragucci applies them as
# it applies any repo: one run per root, in waves in dependency order. Nothing
# here makes the waves one transaction; a wave that applied stays applied when
# a later one fails. Scenario 6 (b-composed) turns on waves.compose in its own
# pull request: the roots it reaches plan as one plan and apply as one apply,
# each keeping its own state, and that is not one transaction either.
#
# demo.json is written to <reports bucket>/<prefix>/demo.json in floci at every
# step:
#
#   { "intro": "Big Terraform setups are split into separate states, ...",
#     "tool": "terraform", "repo": "<admin>/demo",
#     "cycle": 12, "scenario": "b-waves", "name": "a new subnet", "title": "...",
#     "index": 1, "scenarios": 2,
#     "step": "waiting", "label": "Wave 2 stops and waits for a person to approve it. ...",
#     "started_at": "2026-10-20T10:00:00Z",
#     "next": { "action": "approve wave-2", "from": "2026-10-20T10:04:00Z", "at": "2026-10-20T10:04:20Z" },
#     "pull": 41, "commit": "<sha>", "beat": null,
#     "chapter": null, "outside": null,
#     "about": { "changes": "...", "watch": "...", "shows": "..." },
#     "delivery": "Counted from this demo loop's own runs, ..." }
#
# step is one of pull-request, planned, merged, applying, waiting, approved,
# failed, resumed, applied, reset and stalled. next is null at stalled; next.at
# is null while the driver waits on the pipeline rather than on its own clock.
# next.from is when the driver started waiting for that action: a write that
# keeps the same action and at keeps its from, so a reader can draw how far the
# wait has gone. An older driver leaves it out, so readers take it as
# optional. While an estate migration of the cycle writes its resources,
# next.action names it with its count, "split: 2 of 4 moved" ("stamped" for
# an adoption), read from the last line of the migration's progress.jsonl in
# the reports bucket (migration_follow), and goes back to the action before
# once every resource has its line.
# beat is null: no scenario is told in beats now, and the field stays for
# readers that look for it.
# chapter is where the step stands in a scenario told in numbered chapters,
# { "n": 2, "of": 4, "headline": "cluster-a breaks. ...", "short": "cluster-a breaks" },
# a headline per chapter that a viewer reads over the title, which stays the
# same through the cycle, and a short name for each chapter's place on a track.
# Only the fan-out scenarios have chapters (demo_chapter); every other
# scenario's steps, the base's and a reset outside a fourth chapter write null.
# A stalled step keeps the chapter of the step before it.
# outside is an apply made outside the pipeline beside one of its runs, or null:
# { "who": "an operator", "estate": "fo-app-01", "command": "choudoufu apply
#   -target=...", "state": "applying|applied|failed", "started_at": "...",
#   "ended_at": "..." or null, "resources": ["aws_sqs_queue.alarms"],
#   "log": [the last lines of its output] }. Only fan-out-choudoufu writes one
# (operator_beat), from its operator's apply to the end of its cycle.
# highlight is what behold opens as a modal over the step, or null:
# { "title": "...", "body": "..." }, the one thing that step shows a viewer
# should not miss (highlight_title, highlight_body). The fan-out scenarios
# write one on a few steps, and every other step writes null.
# pull and commit are null until the cycle has them. about is the scenario's
# card, read from <tool's tree>/scenarios/<scenario>/about.json at the start of
# its cycle: what the change is, what to watch for, and what it shows. It is
# null when the scenario has none (the base). just lint-docs lints its text.
#
# intro is the problem the whole demo is about, the same in every write: the
# problem field of example-demo/scenarios/intro.json, which just lint-docs lints
# too. name is the scenario's short label ("a new subnet"); title is its
# headline. index is the scenario's 1-based place in this loop's list and
# scenarios is how many that list holds, so "1 of 3". index is null for the
# base, and scenarios is 0 when up writes it, before any loop.
#
# delivery is the line behold's kiosk shows over the delivery (DORA) numbers:
# the delivery field of example-demo/scenarios/intro.json, the same in every
# write, which just lint-docs lints. The numbers are terragucci estate's, from
# the loop's own audit trail: after each cycle's audit the driver runs
# `terragucci estate` on the reports prefix (estate_page), which writes
# estate.json, estate.html, dora.json, history.json and history.html beside
# demo.json and sends the terragucci_dora_* gauges to the stack's collector,
# which Prometheus keeps for the kiosk.
#
# ask, asks, opening and closing drive behold's prompt pane (behold#935) and are
# written only by a scenario with an ask.json, next to its about.json
# (<tool's tree>/scenarios/<scenario>/ask.json); every other scenario's
# demo.json has none of the four. The file's top-level "opening" and "closing"
# strings become demo.json's. Each other key is a step name, and its value is
# one ask object, written as ask, or a list of them for a step with two beats,
# written as asks. An ask is copied as given:
#   { "prompt": "...", "action": null, "reply": "{dependents} resources ...",
#     "light": ["network/terraform_data.subnet"], "paths": true, "ghost": false }
# A step with asks holds ask_secs seconds (see there) in place of HOLD. The steps of a scenario's fix pull request read fix-<step>, and its applied step applied.
#
# tool is the tool the scenario shows (terraform, terragrunt) and repo the forge
# repo its cycle runs on (<admin>/demo, <admin>/demo-terragrunt): the repo whose
# commit, pull request and runs the step names. Every write has both.
#
# Every write is also appended, with an at time, to the cycle's timeline. When
# a cycle ends with reset, the driver publishes it as its tool's latest:
#
#   <prefix>/cycles/<tool>/latest.json and <prefix>/cycles/<tool>/<cycle>.json
#   { "schema": "demo.cycle/v1", "tool": "terragrunt", "repo": "<admin>/demo-terragrunt",
#     "scenario": "tg-planned-outputs", "cycle": 14,
#     "started": "2026-10-20T10:00:00Z", "ended": "2026-10-20T10:02:10Z",
#     "steps": [ { <demo.json as written>, "at": "2026-10-20T10:00:01Z" }, ... ],
#     "runs": [ <the ids of the runs the cycle started, oldest first> ] }
#
# started is the cycle's started_at and ended the reset's at. runs are the ids
# in <prefix>/runs/ that the driver marked (or placed) in the cycle, so a page
# can show the same runs. Each tool keeps its newest 5 <cycle>.json; a publish
# deletes older ones. A cycle that stalled at any step is never published, so
# latest.json is always a cycle that ran to its reset (scripts/demo-cycles.ts).
#
# Beside it, <prefix>/runs/index.json and <prefix>/runs/<id>.json hold the last
# 30 pipeline runs of the repos the loop uses, with their jobs, steps and logs,
# each run with its repo and tool, copied while they run and when they end
# (runs_export, scripts/demo-runs.ts), so behold's kiosk shows them without
# reaching Forgejo. Every DEMO_PRUNE_EVERY-th reset (10) deletes each of those
# repos' runs in Forgejo past the newest DEMO_FORGE_RUNS (100) that have ended,
# so its database stays near one size however long the loop runs. That reset
# also deletes each repo's
# closed pull requests, and their refs/pull/<n>/head, past the newest
# DEMO_FORGE_PULLS (50), never an open one, the newest, or one the bucket's
# cycles or runs name, and has Forgejo run git gc and its Actions cleanup at
# most hourly (scripts/demo-pulls.ts, behold#603). And it deletes each
# project's wave reports in the bucket past the newest DEMO_REPORTS_KEEP (50)
# commits, never a commit the indexes' newest rows, the inventory, the state
# edges or versions, a stored cycle or demo.json name, after dropping those
# runs from index.json, changes.json, states.json, history.json and the report
# entries of audit.jsonl (scripts/demo-reports.ts). Each cycle starts by
# putting its repo's chant/lifecycle back to its base, which up never writes:
# the branch is deleted, as a fresh repo has none, and the cycle's approvals
# make it again. It holds that cycle's gate lines until the repo's next cycle,
# so behold's kiosk can replay them, and the reset's prune drops the
# audit.jsonl ledger entries it no longer holds that are older than the
# project's oldest kept report.
#
# Once a cycle's reset is written, its publish to cycles/, its audit and the
# DORA numbers run in the background (housekeeping_start), so the next cycle
# opens its pull request while they finish.
#
# A step past its time limit (DEMO_LIMIT_*) writes "stalled", resets and goes
# on with the next cycle. The host's watchdog restarts the driver itself if it
# dies; the driver's pid is in <state>/demo/driver.pid while it loops.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$HERE/.." && pwd)"
DEMO="$REPO_ROOT/example-demo"
CMD="${1:-}"; shift || true

log()  { echo "[demo] $*" >&2; }
fail() { log "FAIL: $*"; [ -z "${DEMO_STATE:-}" ] || printf '%s\n' "$*" > "$DEMO_STATE/reason" 2>/dev/null || true; exit 1; }

# shellcheck disable=SC2015
