# A loop's repo is ready: it has a base, and the base names the reviewer.
loop_ready() {
  [ -f "$RSTATE/base.sha" ] || fail "no base snapshot of $REPO; run 'just demo up' first"
  # A base pushed before the driver played two people names the driver's key
  # in .chant/allowed_signers, so the reviewer's seal would not verify.
  local signers
  signers="$(git -C "$RSTATE/base-tree" show "$(cat "$RSTATE/base.sha"):.chant/allowed_signers" 2>/dev/null || true)"
  # A plain-workflow repo approves by review and keeps no signers (up writes none for it).
  tool_plain "$TOOL" || grep -q "^$REVIEWER " <<<"$signers" \
    || fail "the base of $REPO: .chant/allowed_signers does not name $REVIEWER; run 'just demo up' again"
  # Each reset copies app's database back from demo_base, which up keeps.
  if has_db; then
    pg postgres <<<"DO \$\$ BEGIN IF NOT EXISTS (SELECT FROM pg_database WHERE datname = 'demo_base') THEN RAISE 'no demo_base'; END IF; END \$\$" 2>/dev/null \
      || fail "demo-postgres has no database demo_base for $REPO's resets; run 'just demo up' again"
  fi
  people_join
}

case "$CMD" in
  up)
    sync_product_trees
    started=$(now)
    curl -fsS -o /dev/null -X PUT "$FLOCI/$REPORT_BUCKET" || true
    LOOP_TOOLS=()
    # With DEMO_SCENARIOS set, up readies only the tools those scenarios run on (the terraform tree's too, whose
    # example-demo/ every run reads), so a tree that is in the checkout but in no scenario of this host, such as a new
    # demo not yet checked, never stops the demo that is.
    up_tools=" terraform "
    for s in ${DEMO_SCENARIOS:-}; do up_tools+="$(scenario_tool "$s" 2>/dev/null || true) "; done
    for t in "${TOOLS[@]}"; do
      tool_present "$t" || continue
      [ -z "${DEMO_SCENARIOS:-}" ] || [[ "$up_tools" == *" $t "* ]] || { log "up: $t is in no scenario of DEMO_SCENARIOS; not readied"; continue; }
      LOOP_TOOLS+=("$t")
    done
    # DEMO_IMAGE is the terraform tree's image and the fan-out tree's, which
    # installs hashicorp/aws from its mirror. A tree whose roots run on
    # choudoufu names the same image as DEMO_IMAGE_CHOUDOUFU, since it carries
    # the choudoufu binary.
    image_tools=()
    for t in "${LOOP_TOOLS[@]}"; do
      image=""
      # The Terragrunt-on-choudoufu repo has no terragucci.yml to name an image; its workflow names its own (below).
      if tool_tgc "$t"; then image_tools+=("$t"); continue; fi
      if tool_choudoufu "$t"; then image="$DEMO_IMAGE_CHOUDOUFU"
      elif [ "$t" = terraform ] || [ "$t" = tofu-fanout ]; then image="$DEMO_IMAGE"
      fi
      if [ -n "$image" ]; then
        if [ "$t" = atmos-choudoufu ]; then
          image="$DEMO_IMAGE_PLAIN_CHOUDOUFU"
          grep -q "container: $image" "$(tool_tree "$t")/.forgejo/workflows/atmos-choudoufu.yml" \
            || fail "$(tool_tree "$t")/.forgejo/workflows/atmos-choudoufu.yml does not name $image as its container"
        else
          grep -qx "image: $image" "$(tool_tree "$t")/terragucci.yml" \
            || fail "$(tool_tree "$t")/terragucci.yml does not name $image as its image"
        fi
        image_tools+=("$t")
      fi
    done
    if [ "${#image_tools[@]}" -gt 0 ]; then
      if [ -n "$CHOUDOUFU_REF" ]; then
        log "building $DEMO_IMAGE and $DEMO_IMAGE_CHOUDOUFU with choudoufu built from ${CHOUDOUFU_REF:0:10}…"
        choudoufu_args=(--build-arg CHOUDOUFU_FROM=source --build-arg CHOUDOUFU_REF="$CHOUDOUFU_REF")
      else
        log "building $DEMO_IMAGE and $DEMO_IMAGE_CHOUDOUFU with choudoufu $CHOUDOUFU_VERSION…"
        choudoufu_args=()
      fi
      docker build -q -t "$DEMO_IMAGE" -t "$DEMO_IMAGE_CHOUDOUFU" -t "$DEMO_IMAGE_PLAIN_CHOUDOUFU" --build-arg BASE="$(awk '$1 == "tofu" { print $2 }' <<<"$refs")" \
        --build-arg CHOUDOUFU_VERSION="$CHOUDOUFU_VERSION" --build-arg CHANT_VERSION="$CHANT_VERSION" --build-arg CHANT_REF="$CHANT_REPORT_REF" ${choudoufu_args[@]+"${choudoufu_args[@]}"} "$HERE/demo-yodel" >/dev/null \
        || fail "$DEMO_IMAGE did not build from stack/demo-yodel/Dockerfile"
      # The Terragrunt-on-choudoufu repo's jobs run in the choudoufu image with terragrunt added.
      if tool_present terragrunt-choudoufu; then
        log "building $TGC_JOB_IMAGE…"
        docker build -q -t "$TGC_JOB_IMAGE" --build-arg CHOUDOUFU_IMAGE="$DEMO_IMAGE_CHOUDOUFU" \
          --build-arg TERRAGRUNT_IMAGE="$(awk '$1 == "terragrunt" { print $2 }' <<<"$refs")" \
          -f "$HERE/demo-terragrunt-choudoufu.Dockerfile" "$HERE/demo-yodel" >/dev/null \
          || fail "the Terragrunt-on-choudoufu job image did not build: docker build -f stack/demo-terragrunt-choudoufu.Dockerfile stack/demo-yodel"
      fi
      if tool_present terraform; then
        log "starting demo-postgres…"
        docker compose -f "$HERE/docker-compose.yml" --project-name "$TG_PROJECT" --profile demo up -d --wait demo-postgres >/dev/null \
          || fail "demo-postgres did not start"
      fi
      # A choudoufu tree's record store and its front, in the image just built:
      # recreated, so it runs the new one.
      records_front=""
      for t in "${image_tools[@]}"; do
        tool_choudoufu "$t" || continue
        records_up "$(tool_records_bucket "$t")"
        # The Atmos stack names an S3 backend for Atmos to write backend.tf.json from; choudoufu ignores it and publishes outputs there.
        [ "$t" != atmos-choudoufu ] || curl -s -o /dev/null -X PUT "$FLOCI/demo-atmos-choudoufu-state" || true
        records_front=1
      done
      if [ -n "$records_front" ]; then
        log "starting demo-records…"
        docker compose -f "$HERE/docker-compose.yml" --project-name "$TG_PROJECT" --profile demo up -d --wait --force-recreate demo-records >/dev/null \
          || fail "demo-records did not start"
      fi
    fi
    # behold#571: the pipeline's metrics and traces. The demo trees'
    # terragucci.yml send each job's metrics and spans over OTLP to
    # otel-collector:4318 on the stack's network: Prometheus keeps the metrics
    # (prometheus:9090) and Tempo the traces (tempo:3200), both for behold's
    # kiosk. Profile observability-lite: the collector, Prometheus and a small
    # Tempo, no Grafana. Tempo starts on its own, so the metrics come up when
    # it does not. When none start, the jobs run as before: a stage that cannot
    # send says so in its log and carries on.
    if docker compose -f "$HERE/docker-compose.yml" --project-name "$TG_PROJECT" --profile observability-lite up -d --wait otel-collector-lite prometheus >/dev/null 2>&1; then
      log "metrics: the collector and Prometheus are up"
    else
      log "metrics: the collector or Prometheus did not start; each job logs that its metrics were not sent"
    fi
    if docker compose -f "$HERE/docker-compose.yml" --project-name "$TG_PROJECT" --profile observability-lite up -d --wait tempo-lite >/dev/null 2>&1; then
      log "traces: Tempo is up and keeps each job's trace for 24 hours"
    else
      log "traces: Tempo did not start; the jobs' spans still count in the span metrics"
    fi
    [ -f "$DEMO_STATE/cycle" ] || echo 0 > "$DEMO_STATE/cycle"
    CYCLE="$(cat "$DEMO_STATE/cycle")" SCENARIO=base TITLE="The base" ABOUT=null STARTED="$started"
    timeline_start
    : > "$WORK/ready"
    for t in "${LOOP_TOOLS[@]}"; do
      use_repo "$t"
      [ -z "$STATE_BUCKET" ] || curl -fsS -o /dev/null -X PUT "$FLOCI/$STATE_BUCKET" || true
      up_repo
      printf '  %-12s %s/%s\n  %-12s %s\n' "$TOOL" "$URL" "$REPO" "" "$RUN_URL" >> "$WORK/ready"
    done
    log "ready in $(( $(now) - started ))s"
    cat <<OUT

  The demo's bases are applied.

$(cat "$WORK/ready")

  demo.json    $FLOCI/$REPORT_BUCKET/$REPORT_PREFIX/demo.json

  Next: just demo loop
OUT
    ;;

  loop)
    sync_product_trees
    ONCE="" list=()
    for a in "$@"; do
      case "$a" in
        --once) ONCE=1 ;;
        -*) fail "unknown flag '$a' (--once)" ;;
        *) scenario_title "$a" >/dev/null || fail "unknown scenario '$a' (${ALL_SCENARIOS[*]})"; list+=("$a") ;;
      esac
    done
    # No scenario named: DEMO_SCENARIOS, checked like the arguments, or the default list.
    if [ "${#list[@]}" -eq 0 ] && [ -n "${DEMO_SCENARIOS:-}" ]; then
      read -r -a named <<<"$DEMO_SCENARIOS"
      for a in ${named[@]+"${named[@]}"}; do
        scenario_title "$a" >/dev/null || fail "unknown scenario '$a' in DEMO_SCENARIOS (${ALL_SCENARIOS[*]})"
        list+=("$a")
      done
    fi
    [ "${#list[@]}" -gt 0 ] || list=("${SCENARIOS[@]}")
    COUNT="${#list[@]}"
    # The tools the list's scenarios run on, each once, in the order they first come.
    LOOP_TOOLS=()
    for a in "${list[@]}"; do
      t="$(scenario_tool "$a")"
      case " ${LOOP_TOOLS[*]-} " in *" $t "*) ;; *) LOOP_TOOLS+=("$t") ;; esac
    done
    for t in "${LOOP_TOOLS[@]}"; do use_repo "$t"; loop_ready; done
    echo "$$" > "$DEMO_STATE/driver.pid"
    # An earlier driver's background copy is not this one's to wait on.
    mkdir -p "$RUNS_STATE" && : > "$RUNS_PID"
    rm -rf "$BG_DIR"
    CYCLE="$(cat "$DEMO_STATE/cycle" 2>/dev/null || echo 0)"
    SCENARIO=base TITLE="The base" ABOUT=null STARTED="$(now)" INDEX="" ACT="" ACTS=""
    # A driver the watchdog restarted may have left a cycle half done, in any of the loop's repos.
    for t in "${LOOP_TOOLS[@]}"; do
      use_repo "$t"
      timeline_start
      attempt reset_base
      [ "$ATTEMPT" = 0 ] || demo_stalled
    done
    while :; do
      INDEX=0
      for s in "${list[@]}"; do
        INDEX=$((INDEX + 1))
        # The act within its own demo: this scenario's place among the list's scenarios of the same tool, of how many.
        ACT=0 ACTS=0
        for x in "${list[@]}"; do
          [ "$(scenario_tool "$x")" = "$(scenario_tool "$s")" ] || continue
          ACTS=$((ACTS + 1))
          [ "$ACT" -gt 0 ] || { [ "$x" = "$s" ] && ACT="$ACTS"; }
        done
        # This tool's reset from its last scenario may still run in the background.
        bg_join "$(scenario_tool "$s")"
        NEXT_TOOL=""
        if [ "$INDEX" -lt "$COUNT" ]; then NEXT_TOOL="$(scenario_tool "${list[$INDEX]}")"
        elif [ -z "$ONCE" ]; then NEXT_TOOL="$(scenario_tool "${list[0]}")"; fi
        CYCLE=$((CYCLE + 1))
        echo "$CYCLE" > "$DEMO_STATE/cycle"
        : > "$DEMO_STATE/reason"
        use_repo "$(scenario_tool "$s")"
        SCENARIO="$s" TITLE="$(scenario_title "$s")" ABOUT="$(scenario_about "$s")" STARTED="$(now)" PULL="" COMMIT="" OUTCOME=""
        HOLD="$(scenario_hold "$s")"
        timeline_start
        # A step that fails or passes its limit ends the cycle's subshell; the
        # loop writes stalled and resets.
        attempt run_cycle "$s"
        cycled="$ATTEMPT"
        [ "$cycled" = 0 ] || demo_stalled
        rm -rf "$WORK/c$CYCLE"
        # A cycle that ended on its last step has reset behind it (cycle_end).
        if [ "$cycled" = 0 ] && cycle_reset; then ATTEMPT=0; else attempt reset_base; fi
        while [ "$ATTEMPT" != 0 ]; do
          demo_stalled
          sleep "$HOLD"
          : > "$DEMO_STATE/reason"
          attempt reset_base
        done
      done
      [ -z "$ONCE" ] || break
    done
    # The last cycle's housekeeping, before the driver's exit removes its work directory.
    housekeeping_wait
    for t in "${LOOP_TOOLS[@]}"; do bg_join "$t"; done
    ;;
esac
