# A scenario may carry an ask.json beside its about.json:
# <tool's tree>/scenarios/<scenario>/ask.json. Its top level may hold the
# strings "opening" and "closing", and every other key is a step name that maps
# to one ask object or to a list of them (two beats). demo_write copies them
# into demo.json as ask, asks, opening and closing, as given: behold checks the
# types. A fix pull request's steps are keyed fix-<step> (fix-planned,
# fix-approved, fix-applied), so the first pull request's steps are not played
# again; the fix's applied step reads applied. A scenario without the file, or a step without an entry, writes
# nothing, so every other scenario's demo.json is as it was.

ask_file() { # scenario -> its ask.json's path; fails when it has no tree
  local tool
  tool="$(scenario_tool "$1" 2>/dev/null)" || return 1
  echo "$(tool_tree "$tool")/scenarios/$1/ask.json"
}

# {"ask": {...}} for a step with one ask, {"asks": [...]} for a list, else {}.
ask_step() { # ask.json path, step key
  [ -f "$1" ] || { echo '{}'; return 0; }
  jq -c --arg k "$2" '(try .[$k] catch null) as $e
    | if ($e | type) == "array" then {asks: $e} elif ($e | type) == "object" then {ask: $e} else {} end' "$1" 2>/dev/null || echo '{}'
}

# {"opening": "...", "closing": "..."}, each only when the file has it as a string; else {}.
ask_ends() { # ask.json path
  [ -f "$1" ] || { echo '{}'; return 0; }
  jq -c '{opening: (try .opening catch null), closing: (try .closing catch null)} | with_entries(select(.value | type == "string"))' "$1" 2>/dev/null || echo '{}'
}

# The ask fields to merge into the step just written: the scenario's own file, the fix's keys while FIX is set.
# The key a step reads in a file: its name, or while FIX is set fix-<step> when
# the file has one; a fix's applied step, which ends the scenario, reads applied,
# and its other steps read nothing, so the first pull request's asks do not replay.
ask_key() { # ask.json path, step
  if [ -z "${FIX:-}" ]; then echo "$2"; return 0; fi
  if [ -f "$1" ] && jq -e --arg k "fix-$2" 'has($k)' "$1" >/dev/null 2>&1; then echo "fix-$2"
  elif [ "$2" = applied ]; then echo applied
  else echo "fix-$2"; fi
}

ask_fields() { # step
  local f
  # The driver's own setup push (compose_base) is no step of the scenario's story.
  [ -z "${SETUP:-}" ] || { echo '{}'; return 0; }
  f="$(ask_file "$SCENARIO")" || { echo '{}'; return 0; }
  # {pull} in any string becomes "#<number>"; every other {...} token is behold's to fill.
  jq -cn --argjson a "$(ask_step "$f" "$(ask_key "$f" "$1")")" --argjson e "$(ask_ends "$f")" --arg pull "${PULL:+#$PULL}" \
    '($a + $e) | if $pull == "" then . else walk(if type == "string" then gsub("\\{pull\\}"; $pull) else . end) end'
}

# The seconds a step with asks holds, so a viewer can watch each prompt type,
# read the reply and look at the graph. Per ask: 0.6 s of cursor, 0.09 s for
# each character of the prompt (or the action), 0.035 s for each character of
# the reply (a reply with {dependents} counts as 30 characters; the lines of
# an ask's diff count as reply characters) and 3.5 s to read; the step's sum, rounded up, but at least 6 s. An ask with a status and
# no reply holds its prompt's typing plus 1.5 s, with no 6 s floor. A step with no asks, or
# only status-only asks (ask.status with no prompt), does not hold: the pipeline's own time is
# its time. Prints 0 for those.
ask_secs() { # step
  local f
  [ -z "${SETUP:-}" ] || { echo 0; return 0; }
  f="$(ask_file "$SCENARIO")" || { echo 0; return 0; }
  ask_step "$f" "$(ask_key "$f" "$1")" | jq -r '
    [(.ask // empty), ((.asks // [])[])]
    | map(select(type == "object" and ((.prompt // .action // .reply) | type == "string")))
    | if length == 0 then 0 else
        # An ask with a status and no reply holds its prompt typing plus 1.5 s (0 with no prompt): the pipeline runs the rest.
        def plen: ((.prompt // .action // "") | tostring | length);
        def stat: ((.status | type) == "string") and ((.reply | type) != "string");
        (map(if stat then (if plen > 0 then 0.6 + plen * 0.09 + 1.5 else 0 end)
             else 0.6 + plen * 0.09
             + (if (.reply | type) != "string" then 0 elif (.reply | contains("{dependents}")) then 30 else (.reply | length) end) * 0.035
             + (([(.diff // [])[] | tostring | length] | add) // 0) * 0.035
             + 3.5 end) | add | ceil) as $s
        | if all(.[]; stat) then $s elif $s < 6 then 6 else $s end
      end' 2>/dev/null || echo 0
}

# Hold a step that carries an ask for ask_secs. The approved step is written and
# resumed in the same second, so without this the kiosk (which polls every 3 s)
# never shows the person's "You approve the plan" line.
ask_hold() { # step
  local n
  n="$(ask_secs "$1")"
  if [ "${n:-0}" -gt 0 ]; then sleep "$n"; fi
}

# The action and deadline the driver last wrote as next, and when it started
# waiting for them: next.from stays put while a write repeats both.
NEXT_KEY="" NEXT_FROM=""
demo_write() { # step, label, [next action], [next at, epoch seconds]
  local step="$1" label="$2" action="${3:-}" at="${4:-}" at_iso="" next=null chapter ask
  ask="$(ask_fields "$step" 2>/dev/null || echo '{}')"
  [ -n "$ask" ] || ask='{}'
  chapter="$(demo_chapter "$step" 2>/dev/null || echo null)"
  [ -n "$chapter" ] || chapter=null
  view_follow
  [ -z "$at" ] || at_iso="$(iso "$at")"
  if [ -z "$action" ]; then
    NEXT_KEY="" NEXT_FROM=""
  else
    if [ "$action|$at_iso" != "${NEXT_KEY:-}" ] || [ -z "${NEXT_FROM:-}" ]; then
      NEXT_KEY="$action|$at_iso" NEXT_FROM="$(now)"
    fi
    next="$(jq -cn --arg a "$action" --arg f "$(iso "$NEXT_FROM")" --arg t "$at_iso" '{action: $a, from: $f, at: (if $t == "" then null else $t end)}')"
  fi
  jq -n --argjson cycle "$CYCLE" --arg scenario "$SCENARIO" --arg title "$TITLE" --arg step "$step" --arg text "$label" \
    --arg started "$(iso "${STARTED:-$(now)}")" --argjson next "$next" --arg pull "$PULL" --arg commit "$COMMIT" \
    --argjson about "${ABOUT:-null}" --argjson where "$(demo_where)" --argjson chapter "$chapter" --argjson outside "${OUTSIDE:-null}" \
    --argjson highlight "$(highlight_json "$step" 2>/dev/null || echo null)" --argjson ask "$ask" \
    '$where + {cycle: $cycle, scenario: $scenario, title: $title, step: $step, label: $text, started_at: $started, next: $next,
      pull: (if $pull == "" then null else ($pull | tonumber) end), commit: (if $commit == "" then null else $commit end),
      chapter: $chapter, outside: $outside, highlight: $highlight, about: $about} + $ask' \
    > "$DEMO_STATE/demo.json.new"
  mv "$DEMO_STATE/demo.json.new" "$DEMO_STATE/demo.json"
  log "cycle $CYCLE $SCENARIO: $step: $label${MIGRATION_WRITE:+ ($action)}"
  # A migration's count stands in for the action only while it writes: the step's own action is kept to go back to.
  [ -n "${MIGRATION_WRITE:-}" ] || DEMO_STEP="$step" DEMO_LABEL="$label" DEMO_ACTION="$action" DEMO_AT="$at" MIGRATION_SHOWN=""
  demo_put
}

# The estate migrations the scenario's change adds: migrations/<name>.yml in
# its pull/ or push/ tree. Empty for the base and a scenario with none.
scenario_migrations() { # scenario
  local tree f
  tree="$(tool_tree "$(scenario_tool "$1" 2>/dev/null)" 2>/dev/null)" || return 0
  for f in "$tree/scenarios/$1"/{pull,push}/migrations/*.yml; do
    if [ -f "$f" ]; then basename "$f" .yml; fi
  done | sort -u
}

# While a migration of the cycle writes, its count: "split: 2 of 4 moved".
# Wave 1 copies <prefix>/<project>/migrations/<name>/progress.jsonl to the
# bucket every few seconds while the writes land, each line carrying the counts
# so far; this reads the last line of each. Empty when no migration has a line
# from this cycle with resources left.
migration_next() {
  local name line text
  for name in ${MIGRATIONS:-}; do
    line="$(curl -fsS "$FLOCI/$REPORT_BUCKET/$REPORT_PREFIX/forgejo:3000/$REPO/migrations/$name/progress.jsonl" 2>/dev/null | tail -n 1)" || continue
    [ -n "$line" ] || continue
    text="$(jq -r --arg n "$name" --argjson since "${STARTED:-0}" '
      select((.at // "" | sub("\\.[0-9]+"; "") | try fromdateiso8601 catch 0) >= $since and .counts.left > 0)
      | .counts as $c | ($c.moved + $c.stamped + $c.refused + $c.skipped + $c.left) as $t
      | if .outcome == "stamped" or .estate_from == "" then "\($n): \($c.stamped) of \($t) stamped" else "\($n): \($c.moved) of \($t) moved" end' <<<"$line" 2>/dev/null)" || continue
    [ -z "$text" ] || { echo "$text"; return 0; }
  done
  return 0
}

# Each poll of a wait puts the migration's count in next while it writes, at
# most every MIGRATION_EVERY seconds. Once the writes are done it puts the
# step's own action back. Wave 1 copies the progress file every
# TG_PROGRESS_SECONDS (5 unless the tree's terragucci.yml sets it), so a
# migration of a few writes still shows a count between its first and its last.
MIGRATION_AT=0 MIGRATION_SHOWN=""
MIGRATION_EVERY="${DEMO_MIGRATION_EVERY:-2}"
migration_follow() {
  [ -n "${MIGRATIONS:-}" ] && [ -n "${DEMO_STEP:-}" ] || return 0
  [ $(( $(now) - MIGRATION_AT )) -ge "$MIGRATION_EVERY" ] || return 0
  MIGRATION_AT="$(now)"
  local text
  text="$(migration_next)"
  [ "$text" != "$MIGRATION_SHOWN" ] || return 0
  if [ -n "$text" ]; then
    MIGRATION_WRITE=1 demo_write "$DEMO_STEP" "$DEMO_LABEL" "$text"
  else
    MIGRATION_WRITE=1 demo_write "$DEMO_STEP" "$DEMO_LABEL" "$DEMO_ACTION" "$DEMO_AT"
  fi
  MIGRATION_SHOWN="$text"
}

