  fi
  return 0
}

# Every root's state back to the base snapshot, and the states of the roots
# only a scenario adds deleted. A composed run (scenario 6) that stopped part
# way may leave its lock on a state, or a state it could not write kept beside
# it, which the next composed run would write before it plans
# (packages/terragucci/src/compose.ts); a Terragrunt unit's lock is the same
# file. No run is in progress here (quiet, or up before its push), so none
# belongs to a live run. With "missing-ok", a root with no snapshot is skipped.
states_back() { # [missing-ok]
  local root key
  # choudoufu's estates keep records, not states: the push back to the base
  # applies the base tree, which deletes what the cycle added, once the
  # operator's queue, which app-01's estate keeps, is destroyed (operator_back).
  if [ "$TOOL" = choudoufu-fanout ]; then operator_back; return 0; fi
  if [ "$TOOL" = choudoufu-compose ] || [ "$TOOL" = atmos-choudoufu ] || tool_tgc "$TOOL"; then estates_back "${1:-}"; return 0; fi
  if [ "$TOOL" = chant-fanout ] || [ "$TOOL" = chant-compose ]; then stacks_back "${1:-}"; return 0; fi
  for root in "${ROOTS[@]}"; do
    key="$(root_key "$root")"
    if [ -f "$(snapshot "$root")" ]; then
      curl -fsS -o /dev/null -X PUT -H 'content-type: application/json' --data-binary @"$(snapshot "$root")" \
        "$FLOCI/$STATE_BUCKET/$key" || fail "could not write $root's base state back"
    elif [ -z "${1:-}" ]; then
      fail "$root has no base state in $RSTATE/snapshots; run 'just demo up' again"
    fi
  done
  while read -r root key; do
    [ -n "$key" ] || continue
    curl -sS -o /dev/null -X DELETE "$FLOCI/$STATE_BUCKET/$key" || true
  done <<<"$EXTRA_KEYS"
  while read -r root key; do
    [ -n "$key" ] || continue
    curl -sS -o /dev/null -X DELETE "$FLOCI/$STATE_BUCKET/$key.tflock" || true
    curl -sS -o /dev/null -X DELETE "$FLOCI/$STATE_BUCKET/$key.terragucci-unwritten" || true
  done <<<"$BASE_KEYS"$'\n'"$EXTRA_KEYS"
}

# The compose repo's estates back to the base: the base tree applied again with
# choudoufu, as up applied it (estates_apply). Each estate's apply deletes what
# the last cycle added and puts every tag back, so the push back to the base
# has nothing to apply. With "missing-ok", a repo with no base tree yet is skipped.
estates_back() { # [missing-ok]
  if [ ! -d "$RSTATE/base-tree" ]; then
    [ -n "${1:-}" ] || fail "$REPO has no base tree in $RSTATE; run 'just demo up' again"
    return 0
  fi
  estates_apply "$RSTATE/base-tree"
}

# The compose repo's base, applied by the driver outside its pipeline: choudoufu
# apply in each estate of the tree, upstreams first, in the demo's job image on
# the stack's network against floci and the record store, as the pipeline's jobs
# reach them. An estate is applied alone here, reading the recorded outputs of
# the one before it.
#
# Downstreams go first in a cleanup pass: edge, then app, each deleting what the
# last cycle added to it, so network's subnet is not deleted while app's
# instance and network interface still sit in it. On a fresh floci there is
# nothing to read yet, so a cleanup pass that fails is logged and passed over.
# Then network, app and edge apply in order, app and edge reading the values
# network was just put back to.
estates_apply() { # the base tree
  local out image="$DEMO_IMAGE_CHOUDOUFU" script
  log "applying the base of $REPO with choudoufu in $DEMO_IMAGE_CHOUDOUFU…"
  # The Terragrunt repo's units are applied with its own CLI in the job image: downstream units first (edge, then
  # app) to delete what the last cycle added, then every unit in dependency order, as `terragrunt run --all apply`.
  script='set -e; mkdir /w; cd /w; tar xf -; a() { if [ -n "$ATMOS_STACK" ]; then atmos terraform apply "$1" -s "$ATMOS_STACK" -auto-approve; else (cd "${ESTATES_DIR:+$ESTATES_DIR/}$1"; choudoufu init -input=false -no-color >/dev/null; choudoufu apply -auto-approve -input=false -no-color); fi; }; for r in edge app; do a "$r" || echo "cleanup pass: $r did not apply; the pass below applies it again"; done; for r in network app edge; do a "$r"; done'
  if tool_tgc "$TOOL"; then
    image="$TGC_JOB_IMAGE"
    script='set -e; mkdir /w; cd /w; tar xf -; export TG_NON_INTERACTIVE=true TG_NO_COLOR=true TG_LOG_FORMAT=bare; curl -sS -o /dev/null -X PUT "$AWS_ENDPOINT_URL/$TGC_STATE_BUCKET" || true; for u in edge app; do (cd "$u" && terragrunt run -- apply -auto-approve -input=false >/dev/null) || echo "cleanup pass: $u did not apply; the pass below applies it again"; done; terragrunt run --all apply'
  fi
  if ! out="$(tar -C "$1" -cf - --exclude ./.git . | docker run --rm -i --network "$TG_NETWORK" --entrypoint sh \
      -e AWS_ENDPOINT_URL=http://floci:4566 -e AWS_ENDPOINT_URL_S3=http://demo-records:4566 \
      -e AWS_ACCESS_KEY_ID=test -e AWS_SECRET_ACCESS_KEY=test -e AWS_REGION=us-east-1 \
      -e TF_CLI_CONFIG_FILE=/etc/terragucci-demo/tofu-mirror.tfrc -e TF_IN_AUTOMATION=1 -e NO_COLOR=1 -e ATMOS_TELEMETRY_ENABLED=false -e ATMOS_STACK="$([ "$TOOL" = atmos-choudoufu ] && echo dev)" -e ESTATES_DIR="${ESTATES_DIR:-}" -e TGC_STATE_BUCKET="$TGC_STATE_BUCKET" \
      "$image" -c "$script" 2>&1)"; then
    printf '%s\n' "$out" >&2
    fail "choudoufu apply did not apply the base of $REPO"
  fi
}

