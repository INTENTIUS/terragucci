# Run "$@" in a subshell with errexit on, and set ATTEMPT to its status. Called
# as a plain command, never in a condition, where bash would ignore errexit
# inside it: a step that fails or passes its limit ends the subshell there.
attempt() {
  set +e
  ( set -e; "$@" )
  ATTEMPT=$?
  set -e
}

# The base of the repo use_repo points at: its tree less its scenarios, the
# pipeline init writes, and the reviewer's key in .chant/allowed_signers. It is
# the commit every reset forces main back to. The admin pushes it, out of band:
# no wave judges it as a change, because each wave's rule is read at the commit
# before the one it applies, and the base is never in the range after it.
up_repo() {
  local sha root
  if ! api -o /dev/null "$URL/api/v1/repos/$REPO" 2>/dev/null; then
    api -o /dev/null -H 'content-type: application/json' -X POST \
      -d "$(jq -cn --arg n "${REPO#*/}" --arg d "$(repo_description)" '{name: $n, description: $d, private: false, auto_init: false, default_branch: "main"}')" \
      "$URL/api/v1/user/repos"
  fi
  api -o /dev/null -H 'content-type: application/json' -X PATCH -d '{"has_actions":true}' "$URL/api/v1/repos/$REPO"
  # Atmos keys each stored plan by the commit that planned it, the pull
  # request's head, so the Atmos repo merges fast-forward only: the merge
  # pushes that same commit, and the deploy finds the plans the reviewer saw.
  if [ "$TOOL" = atmos-choudoufu ]; then
    api -o /dev/null -H 'content-type: application/json' -X PATCH \
      -d '{"allow_fast_forward_only_merge":true,"default_merge_style":"fast-forward-only","allow_merge_commits":false,"allow_rebase":false,"allow_rebase_explicit":false,"allow_squash_merge":false}' \
      "$URL/api/v1/repos/$REPO" || fail "could not make $REPO merge fast-forward only"
  fi
  people_join
  # The new base is built in base-tree.new and replaces base-tree, beside
  # base.sha, only once it applied. An up that fails part way leaves the last
  # base-tree and base.sha as they were, so the loop of this release or of the
  # one before still finds its base commit there.
  local bt="$RSTATE/base-tree.new"
  rm -rf "$bt"
  mkdir -p "$bt"
  (cd "$TREE" && tar cf - --exclude ./scenarios --exclude ./node_modules .) | (cd "$bt" && tar xf -)
  # The chant trees carry chant's pipeline; the others get terragucci's from init.
  if ! tool_chant "$TOOL" && ! tool_tgc "$TOOL" && [ "$TOOL" != atmos-choudoufu ]; then
    (cd "$bt" && "$TERRAGUCCI" init >/dev/null) || fail "terragucci init failed on $(tool_tree "$TOOL")"
  fi
  if ! tool_tgc "$TOOL"; then mkdir -p "$bt/.chant"; fi
  if ! tool_tgc "$TOOL"; then echo "$REVIEWER $(cut -d' ' -f1,2 "$REVIEWER_KEY.pub")" > "$bt/.chant/allowed_signers"; fi
  # chant's pull-request gate names the reviewer as the forge does (chant_note).
  ! tool_chant "$TOOL" || echo "forgejo@$CHANT_FORGE_HOST:$REVIEWER $(cut -d' ' -f1,2 "$REVIEWER_KEY.pub")" >> "$bt/.chant/allowed_signers"
  # The snapshots an older release kept in <state>/base, copied once (snapshot).
  if [ ! -d "$RSTATE/snapshots" ] && [ -d "$RSTATE/base" ]; then
    mkdir -p "$RSTATE/snapshots"
    cp -p "$RSTATE/base/"*.tfstate "$RSTATE/snapshots/" 2>/dev/null || true
  fi
  # floci may still hold the states of a cycle the driver left part way (a
  # restart after the checkout moved): writing the last base snapshot back
  # first, as the reset does, leaves the base's pipeline nothing to destroy,
  # which gate: on-destructive would otherwise hold for an approval.
  if [ -d "$RSTATE/snapshots" ]; then
    states_back missing-ok
    log "wrote the last base snapshot of $REPO back to floci before pushing the base"
  fi
  # app's database starts anew, and app's state goes with it, so the base's
  # pipeline creates app's migrations again and SQL Yodeler applies them. The
  # base gets a parent commit: SQL Yodeler's wave reads its gate (gate never in
  # app/schema/yodel-waves.json) at the commit before the one it applies.
  if has_db; then
    db_fresh || fail "could not make database demo in demo-postgres"
    curl -sS -o /dev/null -X DELETE "$FLOCI/$STATE_BUCKET/$(root_key app)" || true
    (cd "$bt" && git init -q -b main && git add -A \
      && git -c user.email=example@terragucci.local -c user.name=terragucci -c commit.gpgsign=false commit -q -m "The demo's base, before its pipeline") \
      || fail "could not commit the base's parent"
  fi
  if tool_chant "$TOOL"; then
    chant_base_apply "$bt"
    # [skip ci]: Forgejo starts no run for this push, nor for each reset's push back to it.
    sha="$(push_tree "$bt" "$REPO" main "The demo's base: $(roots_words) [skip ci]")"
    log "pushed the base to $REPO's main at ${sha:0:8}, applied outside its pipeline"
    RUN_URL="(applied outside the pipeline)"
  elif [ "$TOOL" = choudoufu-compose ] || [ "$TOOL" = atmos-choudoufu ] || tool_tgc "$TOOL"; then
    # The composed estates' first apply would wait for an approval (the values network's subnet gives are read
    # before they exist), which an up cannot give: the driver applies the base itself, as for the chant repos.
    estates_apply "$bt"
    sha="$(push_tree "$bt" "$REPO" main "The demo's base: $(roots_words) [skip ci]")"
    log "pushed the base to $REPO's main at ${sha:0:8}, applied outside its pipeline"
    RUN_URL="(applied outside the pipeline)"
  else
    sha="$(push_tree "$bt" "$REPO" main "The demo's base: $(roots_words)")"
    log "pushed the base to $REPO's main at ${sha:0:8}; the pipeline applies every root…"
    wait_run "$REPO" "$sha"
    if [ "$RUN_STATUS" != success ]; then
      print_logs "$REPO" "$RUN_ID"
      fail "the base's pipeline on $REPO ended '$RUN_STATUS'"
    fi
  fi
  # The fan-out stacks and estates keep no Terraform state to snapshot: each reset applies the base again.
  if [ "$TOOL" != chant-fanout ] && [ "$TOOL" != chant-compose ] && [ "$TOOL" != choudoufu-fanout ] && [ "$TOOL" != choudoufu-compose ] &&  ! tool_tgc "$TOOL" && [ "$TOOL" != atmos-choudoufu ]; then
    mkdir -p "$RSTATE/snapshots"
    for root in "${ROOTS[@]}"; do
      curl -fsS -o "$(snapshot "$root")" "$FLOCI/$STATE_BUCKET/$(root_key "$root")" || fail "$root has no state in floci after the base applied"
    done
  fi
  ! has_db || db_snapshot || fail "could not keep database demo as demo_base"
  rm -rf "$RSTATE/base-tree"
  mv "$bt" "$RSTATE/base-tree"
  echo "$sha" > "$RSTATE/base.sha"
  COMMIT="$sha"
  runs_mark base
  demo_write reset "$(base_label)" "start the first cycle"
}

# A chant repo's base, applied by the admin outside its pipeline: `chant run
# --components all` in the tool's job image, the one its jobs run in, on the
# stack's network against floci. Its pull-request loop cannot
# apply a first base: app and edge read outputs that network and app do not
# have yet, and a pull request's plan reads only outputs that exist
# (chant#3999); and its apply job refuses a push no pull request merged. The
# fan-out tree's templates are built first, as its jobs build them, since
# cfn-deploy applies dist/; each reset applies its base again this way.
chant_base_apply() { # the base tree
  local out image build=""
  image="$(tool_image "$TOOL")"
  grep -qF "container: $image" "$1/.forgejo/workflows/chant-pr.yml" \
    || fail "$(tool_tree "$TOOL")/.forgejo/workflows/chant-pr.yml does not run in $image, the image up builds"
  [ "$TOOL" != chant-fanout ] || build='ln -s /opt/demo-chant-fanout/node_modules node_modules; npm run build >/dev/null;'
  [ "$TOOL" != chant-compose ] || build='ln -s /opt/demo-chant-compose/node_modules node_modules; npm run build >/dev/null;'
  log "applying the base of $REPO with chant run in $image (a minute or two)…"
  if ! out="$(tar -C "$1" -cf - --exclude ./.git . | docker run --rm -i --network "$TG_NETWORK" \
      -e AWS_ENDPOINT_URL=http://floci:4566 -e AWS_ACCESS_KEY_ID=test -e AWS_SECRET_ACCESS_KEY=test -e AWS_REGION=us-east-1 \
      "$image" sh -c "set -e; mkdir /w; cd /w; tar xf -; $build chant run --components all --env demo --no-release-record" 2>&1)"; then
    printf '%s\n' "$out" >&2
    fail "chant run --components all did not apply the base of $REPO"
  fi
}

repo_description() {
  case "$TOOL" in
    terraform) echo "The terragucci demo: four roots of terraform_data, a change across their states" ;;
    chant) echo "The terragucci demo on chant: three components of terraform_data, planned on each pull request and applied in waves" ;;
    chant-fanout) echo "The terragucci demo on chant: fifteen CloudFormation stacks in three waves, where a failure holds only what depends on it" ;;
    chant-compose) echo "chant's composed run: network, app and edge as three CloudFormation stacks, planned together and applied under one approval" ;;
    tofu-fanout) echo "The terragucci demo's fan-out: fifteen roots of SQS queues and DynamoDB tables in three waves, where a failure blocks only what depends on it" ;;
    choudoufu-fanout) echo "The terragucci demo's fan-out on choudoufu: fifteen estates with no state files, where two applies to one estate both land" ;;
    compose) echo "The terragucci demo's composed run: network, app and edge planned together and applied in one apply, each with its own state" ;;
    choudoufu-compose) echo "The terragucci demo's composed run on choudoufu: network, app and edge estates in one record store, planned and applied across estates" ;;
