clone_main() { # dir
  git clone -q "$REMOTE" "$1" 2>/dev/null || fail "could not clone $REPO"
}

# The run a push, merge or comment started: the first one newer than BEFORE of
# that event (and on that sha, when given). Sets RUN_ID.
# With RUN_SOFT=1, no run within the limit returns 1 instead of failing.
run_started() { # before id, event, [sha]
  local before="$1" event="$2" sha="${3:-}" deadline=$(( $(now) + LIMIT_START )) id
  while :; do
    runner_watch
    runs_export
    id="$(runs | jq -r --argjson b "$before" --arg e "$event" --arg s "$sha" \
      '[.[] | select(.id > $b and .event == $e and ($s == "" or (.head_sha // .commit_sha) == $s))] | min_by(.id) | .id // empty' || true)"
    if [ -n "$id" ]; then RUN_ID="$id"; return 0; fi
    if [ "$(now)" -ge "$deadline" ]; then
      [ -z "${RUN_SOFT:-}" ] || return 1
      fail "no $event run started within ${LIMIT_START}s"
    fi
    sleep "$POLL"
  done
}

# Whether run RUN_ID is done but for its tips job: it has a tips job that has
# not ended, and every other job succeeded or was skipped. The tips job runs
# after the last wave and only opens pull requests of advice (terragucci
# respond tips). It writes no wave report, roster, migration record or
# progress, and demo.json is the driver's own, so nothing behold reads waits
# on it. A wave that failed or waits is a job that failed, which this never
# passes, and the tips job behind it is skipped anyway.
only_tips_left() { # jobs JSON (Forgejo's /actions/runs/<id>/jobs)
  jq -e '
    def ended: .status == "success" or .status == "failure" or .status == "cancelled" or .status == "skipped";
    (if type == "array" then . else [] end) as $jobs
    | ($jobs | map(select(.name != "tips"))) as $rest
    | ($rest | length) > 0
      and ($rest | all(.status == "success" or .status == "skipped"))
      and ($jobs | any(.name == "tips" and (ended | not)))' <<<"$1" >/dev/null 2>&1
}

# Whether the job that runs the composed apply has succeeded: apply-wave-1,
# which carries "apply as one composed run in wave 1 (compose:wave-1)" in a
# compose repo. Waves 2 and 3 and tips after it have nothing to apply, and
# nothing the viewer sees waits on them, so for the choudoufu compose repo the
# driver writes applied at this point instead of waiting about 8 s more. Only
# run_ended asks, so quiet still waits for the whole run before a reset pushes.
composed_apply_done() { # jobs JSON
  [ "$TOOL" = choudoufu-compose ] || return 1
  jq -e '(if type == "array" then . else [] end) | any(.name == "apply-wave-1" and .status == "success")' <<<"$1" >/dev/null 2>&1
}

# Whether every job of a run has ended (Forgejo's /actions/runs/<id>/jobs): a
# run Forgejo marks failed as soon as one wave fails can still have later waves
# running or waiting, which start after a failure and block only the roots it
# holds (terragucci#1161). A reply that is no job list counts as ended, as
# before this check.
jobs_ended() { # jobs JSON
  [ -n "$1" ] || return 0
  jq -e '
    def ended: .status == "success" or .status == "failure" or .status == "cancelled" or .status == "skipped";
    if type == "array" then all(.[]; ended) else true end' <<<"$1" >/dev/null 2>&1
}

# Wait for run RUN_ID to end, every job of it (jobs_ended), or for its waves to
# have ended with only its tips job left (only_tips_left), which counts as
# success. The choudoufu compose repo's run counts as success once its composed
# apply has (composed_apply_done). Sets RUN_STATUS and RUN_URL.
run_ended() { # limit
  local deadline=$(( $(now) + $1 )) run status=""
  while :; do
    runner_watch
    runs_export
    migration_follow
    run="$(api "$URL/api/v1/repos/$REPO/actions/runs/$RUN_ID" 2>/dev/null || true)"
    status="$(jq -r '.status // empty' <<<"$run" 2>/dev/null || true)"
    case "$status" in
      success|failure|cancelled|skipped)
        jobs_ended "$(api "$URL/api/v1/repos/$REPO/actions/runs/$RUN_ID/jobs" 2>/dev/null || true)" && break
        # Forgejo marked the run as ended while a later wave still runs: its log is not complete yet.
        ;;
    esac
    if [ -n "$status" ] && only_tips_left "$(api "$URL/api/v1/repos/$REPO/actions/runs/$RUN_ID/jobs" 2>/dev/null || true)"; then
      log "run $RUN_ID: its waves ended; the driver goes on while its tips job runs"
      status=success
      break
    fi
    if [ -n "$status" ] && composed_apply_done "$(api "$URL/api/v1/repos/$REPO/actions/runs/$RUN_ID/jobs" 2>/dev/null || true)"; then
      log "run $RUN_ID: the composed apply succeeded; the driver goes on while its later waves and tips job end"
      status=success
      break
    fi
    [ "$(now)" -lt "$deadline" ] || fail "run $RUN_ID did not end within ${1}s (last status: ${status:-none})"
    sleep "$POLL"
  done
  runs_export force
  RUN_STATUS="$status"
  RUN_URL="$(jq -r '.html_url // empty' <<<"$run" | sed "s#^http://forgejo:3000#$URL#")"
}

# What run RUN_ID ended in. Sets OUTCOME (applied, waiting, migrate, refused,
# failed or cancelled) and WAVE (the wave that waited, refused or failed, when
# the run says). migrate is a migration in wave 1 that waits for an approval of
# its digest (packages/terragucci/src/migrate.ts), named in MIGRATION and
# MIGRATE_DIGEST. A run after an approval may print the approved migration's
# wait again before it finds the approval (chant#3847), so a migration this
# cycle approved at that digest (MIGRATIONS_APPROVED) is not read as waiting.
MIGRATION="" MIGRATE_DIGEST="" MIGRATIONS_APPROVED=""
run_outcome() {
  local logs line job m d
  OUTCOME="" WAVE=""
  case "$RUN_STATUS" in
    success) OUTCOME=applied; return 0 ;;
    cancelled|skipped) OUTCOME=cancelled; return 0 ;;
  esac
  logs="$(run_logs "$REPO" "$RUN_ID" 2>/dev/null || true)"
  if line="$(grep -oE 'migration [^ ]+ waits for an approval of digest [^ ]+\. Read' <<<"$logs" | tail -1)" && [ -n "$line" ]; then
    m="${line#migration }" d="${line##* of digest }"
    m="${m%% *}" d="${d%. Read}"
    case " $MIGRATIONS_APPROVED " in
      *" $m@$d "*) ;;
      *) OUTCOME=migrate MIGRATION="$m" MIGRATE_DIGEST="$d" WAVE=1; return 0 ;;
    esac
  fi
  # A wave whose plans moved after their approval (apply.ts) prints the approve
  # line too, so the refusal is read first.
  if line="$(grep -oE 'wave [0-9]+ changed after it was approved' <<<"$logs" | awk 'NR == 1')" && [ -n "$line" ]; then
    OUTCOME=refused; WAVE="$(grep -oE '[0-9]+' <<<"$line" | awk 'NR == 1')"; return 0
  fi
  if line="$(grep -oE 'terragucci approve wave-[0-9]+' <<<"$logs" | awk 'NR == 1')" && [ -n "$line" ]; then
    OUTCOME=waiting; WAVE="${line##*wave-}"; return 0
  fi
  OUTCOME=failed
  job="$(api "$URL/api/v1/repos/$REPO/actions/runs/$RUN_ID/jobs" 2>/dev/null | jq -r '[.[] | select(.status == "failure") | .name][0] // empty' || true)"
  WAVE="$(grep -oE 'wave-[0-9]+' <<<"$job" | awk 'NR == 1' | sed 's/wave-//' || true)"
}

# The reviewer's approval: chant approve as the reviewer's principal, sealed
# with the reviewer's key, from the reviewer's own clone, so the ledger commit
# chant pushes is the reviewer's too. The reviewer had no hand in the change.
approve_wave() { # wave number
  local clone="$WORK/approve-$CYCLE-$1-$RANDOM" out
  git clone -q "$REVIEWER_REMOTE" "$clone" 2>/dev/null || fail "$REVIEWER could not clone $REPO"
  git -C "$clone" config user.name "$REVIEWER"
  git -C "$clone" config user.email "$REVIEWER@terragucci.local"
  out="$(cd "$clone" && "$CHANT" approve tf-apply "wave-$1" --actor "$REVIEWER" --sign "$REVIEWER_KEY" 2>&1)" \
    || { echo "$out" >&2; fail "chant approve tf-apply wave-$1 failed"; }
}

# Start the merged pull request's waves again, as the author: /terragucci
# apply on it with the author's write token (packages/terragucci/src/resume.ts
# does the same for Forgejo). The rule does not judge the commenter, only who
# opened, wrote and committed the change and the tokens' users, and the author
# is one of those anyway. Sets RUN_ID to the comment's run.
resume_pull() {
  local before
  before="$(last_run_id)"
  as_author -o /dev/null -H 'content-type: application/json' -X POST -d '{"body":"/terragucci apply"}' \
    "$URL/api/v1/repos/$REPO/issues/$PULL/comments" || fail "could not comment /terragucci apply on pull request $PULL"
  run_started "$before" issue_comment
  runs_mark resume "$PULL"
}

