#!/usr/bin/env python3
"""Write the terralith scenario's pull requests from the generated tree.

    python3 scripts/phases.py        (from example-demo-terralith/)

Reads terralith/iam.tf, versions.tf and logs.tf and writes each beat's
files under scenarios/terralith-<beat>/pull:

  adopt   terralith/state.tf as a live block, and migrations/adopt.yml
  split   the three team roots, terralith/ without their resources, and
          migrations/split.yml
  team    team-b's iam.tf with one more action in an inline policy, for
          team-b's own repository, where the root is the repository's top
  cross   terralith/outputs.tf, and each team's log group reading it

Each team holds two of terralith-gen's named teams: team-a has team_0000 and
team_0001, team-b team_0002 and team_0003, team-c team_0004 and team_0005,
each with its log group from logs.tf. Names keep the generator's prefix,
"tl"; stack/demo.sh writes the cycle's prefix over it.
"""
import os
import re

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(HERE, "scenarios")
TEAMS = {"team-a": ["0000", "0001"], "team-b": ["0002", "0003"], "team-c": ["0004", "0005"]}
RECORDS = "demo-terralith-records"


def read(*p):
    with open(os.path.join(HERE, *p)) as f:
        return f.read()


def write(rel, text):
    path = os.path.join(OUT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


def blocks(text):
    """Each top-level block as (type, name, text), and the header before the first."""
    out, i = [], 0
    head = None
    for m in re.finditer(r'^resource "([^"]+)" "([^"]+)" \{', text, re.M):
        if m.start() < i:
            continue
        if head is None:
            head = text[: m.start()]
        depth, j = 0, m.end() - 1
        while True:
            c = text[j]
            if c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
                if depth == 0:
                    break
            j += 1
        out.append((m.group(1), m.group(2), text[m.start() : j + 1]))
        i = j + 1
    return head or "", out


def live(estate):
    return (
        "terraform {\n  live {\n"
        f'    estate = "{estate}"\n\n'
        f'    record_store "s3" {{\n      bucket = "{RECORDS}"\n    }}\n'
        "  }\n}\n"
    )


TAGGABLE = ("aws_iam_role", "aws_iam_policy", "aws_iam_instance_profile", "aws_cloudwatch_log_group")


def main():
    iam_head, iam = blocks(read("terralith", "iam.tf"))
    _, logs = blocks(read("terralith", "logs.tf"))
    versions = read("terralith", "versions.tf").replace("Generated by tools/terralith-gen.", "Copied from the terralith's versions.tf.")
    owner = {}
    for team, ids in TEAMS.items():
        for n in ids:
            owner[f"team_{n}_"] = team
    def team_of(name):
        for p, t in owner.items():
            if name.startswith(p):
                return t
        return None

    # adopt: the backend block becomes a live block.
    write("terralith-adopt/pull/terralith/state.tf", "# The terralith as a choudoufu estate: its resources carry the ownership tags\n# live-import stamps, and it keeps no state file.\n" + live("tl-terralith"))
    write(
        "terralith-adopt/pull/migrations/adopt.yml",
        "# Adopt the terralith: choudoufu live-import reads its s3 state once and\n"
        "# stamps tofu-estate and tofu-address on every resource it verifies. The\n"
        "# state file is left in the bucket as it was.\n"
        "backends:\n  - root: terralith\n    from:\n      backend: s3\n      config:\n"
        "        bucket: demo-terralith-state\n        key: tl-terralith.tfstate\n        region: us-east-1\n"
        "        use_lockfile: true\n        use_path_style: true\n",
    )

    # split: the team roots, the terralith without their resources, and the moves.
    kept = [b for b in iam if team_of(b[1]) is None]
    write("terralith-split/pull/terralith/iam.tf", iam_head + "\n\n".join(b[2] for b in kept) + "\n")
    write("terralith-split/pull/terralith/logs.tf", "# The team log groups moved to the team roots (team-a, team-b and team-c).\n")
    moves = ["# Split the terralith: each team's resources move to the team's own estate.",
             "# choudoufu live-mv -from-estate rewrites each resource's tags, run in the",
             "# root it moves to. The untaggable ones (inline policies and attachments)",
             "# follow their role with no write of their own.",
             "moves:"]
    for team, ids in TEAMS.items():
        mine = [b for b in iam if team_of(b[1]) == team]
        log = [b for b in logs if b[1] == team.replace("-", "_")]
        write(f"terralith-split/pull/{team}/state.tf", f"# {team}'s estate, carved from the terralith.\n" + live(f"tl-{team}"))
        write(f"terralith-split/pull/{team}/versions.tf", versions)
        write(f"terralith-split/pull/{team}/iam.tf", f"# {team}'s identity resources, moved from the terralith's iam.tf.\n\n" + "\n\n".join(b[2] for b in mine) + "\n")
        write(f"terralith-split/pull/{team}/logs.tf", f"# {team}'s log group, moved from the terralith's logs.tf.\n\n" + log[0][2] + "\n")
        moves += [f"  - from: terralith", f"    to: {team}", "    addresses:"]
        moves += [f"      - {t}.{n}" for t, n, _ in mine + log if t in TAGGABLE]
    write("terralith-split/pull/migrations/split.yml", "\n".join(moves) + "\n")

    # team: team-b changes its own inline policy, in team-b's repository.
    mine = [b for b in iam if team_of(b[1]) == "team-b"]
    changed = []
    for t, n, text in mine:
        if n == "team_0002_inline":
            new = text.replace('"dynamodb:DeleteItem"]', '"dynamodb:DeleteItem", "dynamodb:Query"]')
            assert new != text, "team_0002_inline's actions are not where phases.py expects them"
            text = new
        changed.append(text)
    write("terralith-team/pull/iam.tf", "# team-b's identity resources, moved from the terralith's iam.tf.\n\n" + "\n\n".join(changed) + "\n")

    # cross: the terralith publishes log_retention_days, and each team's log group reads it.
    write(
        "terralith-cross/pull/terralith/outputs.tf",
        "# A setting every team reads: each team root's log group takes its retention\n# from here, through data.terraform_estate_outputs.\noutput \"log_retention_days\" {\n  value = 14\n}\n",
    )
    for team in TEAMS:
        name = team.replace("-", "_")
        write(
            f"terralith-cross/pull/{team}/logs.tf",
            f"# {team}'s log group, its retention read from the terralith's estate.\n\n"
            f'resource "aws_cloudwatch_log_group" "{name}" {{\n'
            f'  name              = "tl-{team}-logs"\n'
            f"  retention_in_days = data.terraform_estate_outputs.platform.values.log_retention_days\n}}\n\n"
            f'data "terraform_estate_outputs" "platform" {{\n  estate = "tl-terralith"\n  names  = ["log_retention_days"]\n}}\n',
        )


if __name__ == "__main__":
    main()
